def _compute_dimension_match(
    val_a: Optional[str],
    val_b: Optional[str],
    synonym_clusters: Optional[List[Set[str]]] = None
) -> float:
    """
    Computes keyword matching and cluster overlap for a single method dimension.
    """
    if not val_a or not val_b:
        return 0.15  # Baseline neutral when dimension unspecified

    import re
    tokens_a = set(re.findall(r'\b[a-zA-Z0-9]{3,}\b', str(val_a).lower()))
    tokens_b = set(re.findall(r'\b[a-zA-Z0-9]{3,}\b', str(val_b).lower()))

    if not tokens_a or not tokens_b:
        return 0.15

    # Direct token intersection
    intersection = tokens_a.intersection(tokens_b)
    stop = {"the", "and", "for", "with", "from", "into", "during", "after", "that", "this", "were", "been"}
    meaningful_inter = intersection - stop

    if meaningful_inter:
        min_len = max(1, min(len(tokens_a - stop), len(tokens_b - stop)))
        ratio = len(meaningful_inter) / min_len
        if len(meaningful_inter) >= 2 or ratio >= 0.50:
            return round(min(1.0, 0.75 + (ratio * 0.25)), 2)
        return 0.70

    # Cluster overlap check
    if synonym_clusters:
        for cluster in synonym_clusters:
            has_a = bool(tokens_a.intersection(cluster))
            has_b = bool(tokens_b.intersection(cluster))
            if has_a and has_b:
                return 0.85

    return 0.05  # Dissimilar dimension

def _get_val(obj: Any, key: str, default: Any = None) -> Any:
    if obj is None:
        return default
    if isinstance(obj, dict):
        return obj.get(key, default)
    return getattr(obj, key, default)


