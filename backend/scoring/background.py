def check_travel_feasibility(
    suspect_location: Optional[str] = None,
    scene_location: Optional[str] = None,
    time_window_minutes: Optional[float] = None,
    distance_km: Optional[float] = None
) -> Dict[str, Any]:
    """
    Feasibility check: uses timeline engine concepts to test whether the suspect
    could physically be at the scene during the relevant time window.
    Blocks impossible spatiotemporal combinations.
    """
    if not suspect_location or not scene_location or suspect_location.strip().lower() == scene_location.strip().lower():
        return {
            "status": "physically_feasible",
            "feasibility_multiplier": 1.0,
            "explanation": "Suspect is in immediate vicinity or co-located with scene during time window.",
            "is_blocked": False
        }
    
    dist = distance_km or 25.0
    time_mins = time_window_minutes if time_window_minutes is not None else 60.0
    
    # Maximum reasonable travel speed in transit/road: 120 km/h (2 km/min)
    min_time_required = (dist / 120.0) * 60.0
    
    if time_mins < min_time_required:
        return {
            "status": "physically_impossible",
            "feasibility_multiplier": 0.05,
            "explanation": f"Physically impossible: traversing {dist:.1f} km requires at least {min_time_required:.1f} minutes, but time window was {time_mins:.1f} minutes. Combination blocked.",
            "is_blocked": True
        }
    elif time_mins < min_time_required * 1.5:
        return {
            "status": "borderline",
            "feasibility_multiplier": 0.75,
            "explanation": f"Borderline travel feasibility: {dist:.1f} km transit requires {min_time_required:.1f} minutes, leaving a very narrow margin in the {time_mins:.1f} minute window.",
            "is_blocked": False
        }
    else:
        return {
            "status": "physically_feasible",
            "feasibility_multiplier": 1.0,
            "explanation": f"Physically feasible: {dist:.1f} km is readily traversable within the {time_mins:.1f} minute window.",
            "is_blocked": False
        }

