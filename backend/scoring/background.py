def calculate_record_effective_weight(
    record: Any,
    mo_similarity: Any,
    config: Optional[Dict[str, Any]] = None,
    current_year: float = 2026.0
) -> Dict[str, Any]:
    """
    Applies Legal Controls & Weighting Rules:
      1. Outcome: convictions count most, pending/accused count little, acquittals/discharges count zero.
      2. Recency: older records fade, juvenile records are excluded by default.
      3. Identity: unverified matches are excluded.
      4. Dissimilarity: dissimilar offenses (<0.25 similarity) score zero.
    """
    cfg = config or {}

    # Support dict or float for mo_similarity
    if isinstance(mo_similarity, dict):
        sim_val = float(mo_similarity.get("overall_similarity", mo_similarity.get("mo_similarity_score", 0.0)))
    else:
        sim_val = float(mo_similarity or 0.0)

    # 1. Identity Match Safeguard
    exclude_unverified = _get_val(cfg, "exclude_unverified_identity", True)
    min_id_conf = float(_get_val(cfg, "min_identity_confidence", 0.70))
    id_conf = float(_get_val(record, "identity_match_confidence", 1.0))
    is_verified_id = bool(_get_val(record, "verified_identity", True))

    if exclude_unverified and (not is_verified_id or id_conf < min_id_conf):
        return {
            "effective_weight": 0.0,
            "contribution": 0.0,
            "is_excluded": True,
            "exclusion_reason": f"Identity Safeguard: Identity unverified or confidence ({id_conf:.2f}) < {min_id_conf:.2f}.",
            "recency_factor": 0.0,
            "outcome_factor": 0.0,
            "identity_factor": id_conf
        }

    # 2. Juvenile Justice Safeguard
    exclude_juvenile = _get_val(cfg, "exclude_juvenile_records", True)
    if exclude_juvenile and bool(_get_val(record, "is_juvenile", False)):
        return {
            "effective_weight": 0.0,
            "contribution": 0.0,
            "is_excluded": True,
            "exclusion_reason": "Juvenile Protection Rule: Offense committed while suspect was a juvenile is excluded by default.",
            "recency_factor": 0.0,
            "outcome_factor": 0.0,
            "identity_factor": id_conf
        }

    # 3. Judicial Outcome Rule
    outcome = (_get_val(record, "outcome") or "").strip().lower()
    if outcome == "convicted":
        outcome_factor = 1.00
    elif outcome == "pending":
        outcome_factor = 0.30
    elif outcome in ["merely_accused", "accused"]:
        outcome_factor = 0.15
    elif outcome in ["acquitted", "discharged"]:
        return {
            "effective_weight": 0.0,
            "contribution": 0.0,
            "is_excluded": True,
            "exclusion_reason": f"Judicial Exoneration Rule: Prior {outcome.upper()} counts as zero and is excluded.",
            "recency_factor": 0.0,
            "outcome_factor": 0.0,
            "identity_factor": id_conf
        }
    else:
        outcome_factor = 0.20

    # 4. Recency Rule (Fading curve)
    offense_date = _get_val(record, "offense_date")
    record_year = None
    if offense_date:
        if isinstance(offense_date, str):
            try:
                record_year = float(offense_date[:4])
            except Exception:
                record_year = current_year - 5.0
        elif hasattr(offense_date, "year"):
            record_year = float(offense_date.year)
    if record_year is None:
        record_year = current_year - 5.0

    age_years = max(0.0, current_year - record_year)
    if age_years <= 5.0:
        recency_factor = 1.00
    elif age_years <= 10.0:
        recency_factor = 0.80
    elif age_years <= 15.0:
        recency_factor = 0.65
    elif age_years <= 20.0:
        recency_factor = 0.50
    else:
        recency_factor = 0.30

    # 5. Dissimilarity Rule
    if sim_val < 0.25:
        return {
            "effective_weight": 0.0,
            "contribution": 0.0,
            "is_excluded": True,
            "exclusion_reason": f"Dissimilarity Rule: Modus operandi similarity ({sim_val:.2f}) < 0.25 threshold.",
            "recency_factor": recency_factor,
            "outcome_factor": outcome_factor,
            "identity_factor": id_conf
        }

    # 6. Effective Weight & Net Contribution (scaled up to max cap)
    effective_weight = round(sim_val * outcome_factor * recency_factor * id_conf, 3)
    max_cap = float(_get_val(cfg, "criminal_history_max_cap", 0.10))
    contribution = min(max_cap, round(effective_weight * max_cap, 4))

    return {
        "effective_weight": effective_weight,
        "contribution": contribution,
        "is_excluded": False,
        "exclusion_reason": None,
        "recency_factor": recency_factor,
        "outcome_factor": outcome_factor,
        "identity_factor": id_conf,
        "max_cap": max_cap
    }


def compute_background_scores(
    hypotheses: List[Dict[str, Any]],
    custom_factor_weights: Optional[Dict[str, float]] = None,
    suspect_factors_by_hypothesis: Optional[Dict[Any, List[Dict[str, Any]]]] = None,
    background_config: Optional[Dict[str, Any]] = None,
    prior_records_by_hypothesis: Optional[Dict[Any, List[Dict[str, Any]]]] = None,
    current_case_profile: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """
    Computes Background Plausibility (Priors): 'Background plausibility' (Change 2 & 3)
    A structured assessment of each suspect's access, opportunity, means, motive, 
    alibi status, spatiotemporal travel feasibility, and relevant criminal history (with safeguards),
    converted into a normalized prior.

    Scoring Rules & Legal Controls (Change 3):
      1. Base Composite = weighted sum of access, opportunity, means, and motive.
      2. Strong access plus opportunity raises the prior.
      3. A verified alibi lowers the prior sharply (strongly verified: 0.10x, partially verified: 0.50x).
      4. Missing information leaves factors neutral (0.50 baseline).
      5. Physical travel impossibility blocks impossible combinations (0.05x penalty).
      6. AVOID DOUBLE COUNTING: Post-incident flight, destruction of evidence, and false
         interrogation statements are scored strictly in the ACH Evidence Score (Layer 1).
      7. CRIMINAL HISTORY SAFEGUARDS (Change 3):
         - Evaluated only when relevant across method dimensions (weapon, entry, victim, location, time).
         - Convictions count most, pending/accused counts little, acquittals/discharges count zero.
         - Recency fading curve; juvenile records excluded by default.
         - Unverified identity matches excluded.
         - Strict cap on contribution (max 10% by default); cannot outweigh case evidence.
         - On/off switch supported with dual-evaluation comparison stored.
    """
    if not hypotheses:
        return {"success": False, "hypotheses": [], "sum_priors": 0.0, "factor_weights": {}}

    cfg = background_config or {}
    w_acc = float(cfg.get("access_weight", 0.25))
    w_opp = float(cfg.get("opportunity_weight", 0.25))
    w_means = float(cfg.get("means_weight", 0.15))
    w_mot = float(cfg.get("motive_weight", 0.20))
    w_travel = float(cfg.get("travel_feasibility_weight", 0.15))

    alibi_strong_disc = float(cfg.get("alibi_strongly_verified_discount", 0.10))
    alibi_part_disc = float(cfg.get("alibi_partially_verified_discount", 0.50))
    alibi_contra_mult = float(cfg.get("alibi_contradicted_multiplier", 1.30))
    impossible_penalty = float(cfg.get("impossible_travel_penalty", 0.05))

    # Change 3 Configuration
    include_history = bool(cfg.get("include_criminal_history", True))
    max_history_cap = float(cfg.get("criminal_history_max_cap", 0.10))

    raw_priors_without_hist = {}
    raw_priors_with_hist = {}
    history_contributions = {}
    detailed_factors = {}
    profile_cards = {}
    rationales = {}

    case_profile = current_case_profile or {}

    for h in hypotheses:
        h_id = h["id"]
        is_unknown = bool(
            h.get("is_unknown") or
            h.get("title") == UNKNOWN_HYPOTHESIS_TITLE or
            (h.get("title") and "unknown" in h["title"].lower())
        )

        if is_unknown:
            card_factors = [{
                "factor_type": "open_world_baseline",
                "factor_value": "alternative_perpetrator_baseline",
                "numeric_score": DEFAULT_UNKNOWN_PRIOR / 100.0,
                "effect_on_prior": "neutral",
                "note": f"Modest {DEFAULT_UNKNOWN_PRIOR:.0f}% baseline prior allocated to unlisted suspects / unknown explanation.",
                "source_exhibit": "Open-World Investigative Standard (Change 5)",
                "source_evidence_id": None,
                "confidence": 1.0,
                "is_confirmed": True,
                "entered_by": "System Baseline"
            }]
            detailed_factors[h_id] = {
                "access": 0.50,
                "opportunity": 0.50,
                "means": 0.50,
                "motive": 0.50,
                "alibi_multiplier": 1.0,
                "feasibility_multiplier": 1.0,
                "base_composite": 0.50,
                "history_boost": 0.0,
                "is_unknown": True
            }
            profile_cards[h_id] = card_factors
            rationales[h_id] = f"Modest baseline prior ({DEFAULT_UNKNOWN_PRIOR:.0f}%) representing open-world probability of an unlisted or alternative suspect."
            history_contributions[h_id] = 0.0
            continue

        factors_list = (suspect_factors_by_hypothesis or {}).get(h_id) or (suspect_factors_by_hypothesis or {}).get(str(h_id)) or []

        if factors_list:
            # Structured Suspect Profile Factors (Change 2)
            f_map = {f.get("factor_type"): f for f in factors_list}

            # 1. Access
            acc_f = f_map.get("access", {})
            acc_val = acc_f.get("factor_value", "unconfirmed")
            acc_score = float(acc_f.get("numeric_adjustment") or CHANGE2_FACTOR_NUMERICS.get(acc_val, 0.50))

            # 2. Opportunity
            opp_f = f_map.get("opportunity", {})
            opp_val = opp_f.get("factor_value", "unconfirmed")
            opp_score = float(opp_f.get("numeric_adjustment") or CHANGE2_FACTOR_NUMERICS.get(opp_val, 0.50))

            # 3. Means
            means_f = f_map.get("means", {})
            means_val = means_f.get("factor_value", "standard_physical_capacity")
            means_score = float(means_f.get("numeric_adjustment") or CHANGE2_FACTOR_NUMERICS.get(means_val, 0.50))

            # 4. Motive & Relationship
            mot_f = f_map.get("motive", {})
            mot_val = mot_f.get("factor_value", "none_apparent")
            mot_score = float(mot_f.get("numeric_adjustment") or CHANGE2_FACTOR_NUMERICS.get(mot_val, 0.50))

            # 5. Alibi Status Multiplier
            alibi_f = f_map.get("alibi_status", {})
            alibi_val = (alibi_f.get("factor_value") or "none").lower()
            if "strongly_verified" in alibi_val or "strong" in alibi_val:
                alibi_multiplier = alibi_strong_disc
                alibi_effect = "lowers_prior_sharply"
            elif "partially_verified" in alibi_val or "partial" in alibi_val:
                alibi_multiplier = alibi_part_disc
                alibi_effect = "lowers_prior"
            elif "contradicted" in alibi_val:
                alibi_multiplier = alibi_contra_mult
                alibi_effect = "raises_prior"
            else:
                alibi_multiplier = 1.00
                alibi_effect = "neutral"

            # 6. Travel Feasibility Multiplier
            travel_f = f_map.get("travel_feasibility", {})
            travel_val = (travel_f.get("factor_value") or "physically_feasible").lower()
            if "impossible" in travel_val:
                feasibility_multiplier = impossible_penalty
                feasibility_effect = "blocks_impossible"
            elif "borderline" in travel_val or "tight" in travel_val:
                feasibility_multiplier = 0.75
                feasibility_effect = "tight_margin"
            else:
                feasibility_multiplier = 1.00
                feasibility_effect = "feasible"

            # Base composite prior
            denom = w_acc + w_opp + w_means + w_mot
            base_composite = (
                (acc_score * w_acc) +
                (opp_score * w_opp) +
                (means_score * w_means) +
                (mot_score * w_mot)
            ) / (denom if denom > 0 else 1.0)

            # Modified by alibi verification & spatiotemporal feasibility
            raw_base_prior = max(0.01, base_composite * alibi_multiplier * feasibility_multiplier)

            # Change 3: Criminal History Relevance & Safeguards
            prior_recs = (prior_records_by_hypothesis or {}).get(h_id) or (prior_records_by_hypothesis or {}).get(str(h_id)) or []
            record_contributions = []
            matching_records_count = 0

            for rec in prior_recs:
                mo_res = compute_mo_similarity(rec, case_profile)
                wt_res = calculate_record_effective_weight(rec, mo_res["overall_similarity"], cfg)
                if not wt_res["is_excluded"]:
                    record_contributions.append(wt_res["contribution"])
                    matching_records_count += 1

            total_hist_contrib = sum(record_contributions)
            # Apply strict fixed cap
            capped_hist_boost = min(total_hist_contrib, max_history_cap)
            history_contributions[h_id] = round(capped_hist_boost, 4)

            raw_priors_without_hist[h_id] = raw_base_prior
            raw_priors_with_hist[h_id] = raw_base_prior + capped_hist_boost

            card_factors = []
            for f_key, f_obj, sc, effect in [
                ("access", acc_f, acc_score, "raises_prior" if acc_score >= 0.75 else ("lowers_prior" if acc_score <= 0.35 else "neutral")),
                ("opportunity", opp_f, opp_score, "raises_prior" if opp_score >= 0.75 else ("lowers_prior" if opp_score <= 0.35 else "neutral")),
                ("means", means_f, means_score, "raises_prior" if means_score >= 0.75 else ("lowers_prior" if means_score <= 0.35 else "neutral")),
                ("motive", mot_f, mot_score, "raises_prior" if mot_score >= 0.75 else ("lowers_prior" if mot_score <= 0.35 else "neutral")),
                ("alibi_status", alibi_f, alibi_multiplier, alibi_effect),
                ("travel_feasibility", travel_f, feasibility_multiplier, feasibility_effect)
            ]:
                card_factors.append({
                    "factor_type": f_key,
                    "factor_value": f_obj.get("factor_value") or "unspecified",
                    "numeric_score": sc,
                    "effect_on_prior": effect,
                    "note": f_obj.get("note") or f_obj.get("notes") or "Investigative assessment",
                    "source_exhibit": f_obj.get("source_exhibit_name") or f_obj.get("source_exhibit") or "Case Exhibits",
                    "source_evidence_id": f_obj.get("source_evidence_id"),
                    "confidence": f_obj.get("confidence", 0.85),
                    "is_confirmed": f_obj.get("is_confirmed", True),
                    "entered_by": f_obj.get("entered_by", "Analyst")
                })

            # Add Criminal History factor row (Change 3)
            if capped_hist_boost > 0.005:
                card_factors.append({
                    "factor_type": "criminal_history",
                    "factor_value": f"{matching_records_count} matching prior conviction(s)",
                    "numeric_score": round(capped_hist_boost, 3),
                    "effect_on_prior": "raises_prior",
                    "note": f"Similar prior offense: contributes +{round(capped_hist_boost * 100, 1)}% to background plausibility (Capped at {int(max_history_cap * 100)}%).",
                    "source_exhibit": "Verified Court Judgments / SCRB Records",
                    "source_evidence_id": None,
                    "confidence": 0.95,
                    "is_confirmed": True,
                    "entered_by": "Judicial & Police Records"
                })
            else:
                card_factors.append({
                    "factor_type": "criminal_history",
                    "factor_value": "no_relevant_priors",
                    "numeric_score": 0.0,
                    "effect_on_prior": "neutral",
                    "note": "Criminal history evaluated: no matching or admissible prior records found.",
                    "source_exhibit": "Judicial & SCRB Search",
                    "source_evidence_id": None,
                    "confidence": 1.0,
                    "is_confirmed": True,
                    "entered_by": "Investigator"
                })

            detailed_factors[h_id] = {
                "access": round(acc_score, 2),
                "opportunity": round(opp_score, 2),
                "means": round(means_score, 2),
                "motive": round(mot_score, 2),
                "alibi_multiplier": round(alibi_multiplier, 2),
                "feasibility_multiplier": round(feasibility_multiplier, 2),
                "base_composite": round(base_composite, 3),
                "history_boost": round(capped_hist_boost, 3)
            }
            profile_cards[h_id] = card_factors
            rationales[h_id] = f"Structured Suspect Profile: base {round(base_composite, 2)} with alibi ({alibi_multiplier}x), feasibility ({feasibility_multiplier}x), history (+{round(capped_hist_boost*100, 1)}%)"

        else:
            # Fallback to legacy dictionary or direct background_score if no profile table factors
            factors = h.get("background_factors") or {}
            if isinstance(factors, str):
                try:
                    factors = json.loads(factors)
                except Exception:
                    factors = {}

            f_opp = float(factors.get("opportunity_access", factors.get("opportunity", 5.0)))
            f_mot = float(factors.get("motive_incentive", factors.get("motive", 5.0)))
            f_cap = float(factors.get("capability_means", factors.get("capability", 5.0)))
            f_his = float(factors.get("behavioral_history", factors.get("history", 5.0)))
            f_prx = float(factors.get("target_proximity", factors.get("proximity", 5.0)))

            if "background_score" in h and h["background_score"] is not None and not factors:
                composite = max(0.05, float(h["background_score"]) / 10.0)
            else:
                composite = (
                    (f_opp * 0.25) + (f_mot * 0.25) + (f_cap * 0.20) + (f_his * 0.15) + (f_prx * 0.15)
                ) / 1.0
                composite = max(0.10, composite)

            prior_recs = (prior_records_by_hypothesis or {}).get(h_id) or (prior_records_by_hypothesis or {}).get(str(h_id)) or []
            record_contributions = []
            matching_records_count = 0
            for rec in prior_recs:
                mo_res = compute_mo_similarity(rec, case_profile)
                wt_res = calculate_record_effective_weight(rec, mo_res["overall_similarity"], cfg)
                if not wt_res.get("is_excluded", False):
                    record_contributions.append(wt_res.get("contribution", 0.0))
                    matching_records_count += 1
            total_hist_contrib = sum(record_contributions)
            capped_hist_boost = min(total_hist_contrib, max_history_cap)
            history_contributions[h_id] = round(capped_hist_boost, 4)

            raw_priors_without_hist[h_id] = composite
            raw_priors_with_hist[h_id] = composite + capped_hist_boost

            card_factors = []
            if capped_hist_boost > 0.005:
                card_factors.append({
                    "factor_type": "criminal_history",
                    "factor_value": f"{matching_records_count} matching prior conviction(s)",
                    "numeric_score": round(capped_hist_boost, 3),
                    "effect_on_prior": "raises_prior",
                    "note": f"Similar prior offense: contributes +{round(capped_hist_boost * 100, 1)}% to background plausibility (Capped at {int(max_history_cap * 100)}%).",
                    "source_exhibit": "Verified Court Judgments / SCRB Records",
                    "source_evidence_id": None,
                    "confidence": 0.95,
                    "is_confirmed": True,
                    "entered_by": "Judicial & Police Records"
                })

            detailed_factors[h_id] = {
                "opportunity_access": round(f_opp, 1),
                "motive_incentive": round(f_mot, 1),
                "capability_means": round(f_cap, 1),
                "behavioral_history": round(f_his, 1),
                "target_proximity": round(f_prx, 1),
                "history_boost": round(capped_hist_boost, 3)
            }
            profile_cards[h_id] = card_factors
            rationales[h_id] = factors.get("rationale") or f"Plausibility prior composite: {round(composite, 2)}/10"

    # CHANGE 5: Allocate modest default prior to Unknown hypotheses and normalize
    unknown_ids = [
        h["id"] for h in hypotheses
        if bool(h.get("is_unknown") or h.get("title") == UNKNOWN_HYPOTHESIS_TITLE or (h.get("title") and "unknown" in h["title"].lower()))
    ]
    named_ids = [h["id"] for h in hypotheses if h["id"] not in unknown_ids]

    if unknown_ids and named_ids:
        named_sum_without = sum(raw_priors_without_hist.get(nid, 0.5) for nid in named_ids)
        named_sum_with = sum(raw_priors_with_hist.get(nid, 0.5) for nid in named_ids)

        target_u_frac = (DEFAULT_UNKNOWN_PRIOR / 100.0)
        val_without = (named_sum_without * target_u_frac / max(0.001, (1.0 - target_u_frac))) / len(unknown_ids)
        val_with = (named_sum_with * target_u_frac / max(0.001, (1.0 - target_u_frac))) / len(unknown_ids)

        for uid in unknown_ids:
            raw_priors_without_hist[uid] = max(0.01, val_without)
            raw_priors_with_hist[uid] = max(0.01, val_with)
    elif unknown_ids and not named_ids:
        for uid in unknown_ids:
            raw_priors_without_hist[uid] = 1.0
            raw_priors_with_hist[uid] = 1.0

    # Normalize across all competing hypotheses so sums are strictly 100.0%
    def _normalize_dict(raw_dict):
        sum_r = sum(raw_dict.values()) or 1.0
        norm = {h_id: round((val / sum_r) * 100.0, 1) for h_id, val in raw_dict.items()}
        curr_s = round(sum(norm.values()), 1)
        d = round(100.0 - curr_s, 1)
        if abs(d) > 0.001 and len(norm) > 0:
            top_k = max(norm.items(), key=lambda x: x[1])[0]
            norm[top_k] = round(norm[top_k] + d, 1)
        return norm

    normalized_without_hist = _normalize_dict(raw_priors_without_hist)
    normalized_with_hist = _normalize_dict(raw_priors_with_hist)

    # Active selection based on on/off toggle
    active_normalized = normalized_with_hist if include_history else normalized_without_hist
    active_raw = raw_priors_with_hist if include_history else raw_priors_without_hist

    result_hypos = []
    hypos_without = []
    hypos_with = []

    for h in hypotheses:
        h_id = h["id"]
        res_item = {
            "id": h_id,
            "title": h.get("title", ""),
            "background_score": active_normalized[h_id],
            "background_score_without_history": normalized_without_hist[h_id],
            "background_score_with_history": normalized_with_hist[h_id],
            "history_contribution_pct": round(normalized_with_hist[h_id] - normalized_without_hist[h_id], 1),
            "raw_prior": round(active_raw[h_id], 3),
            "factors": detailed_factors[h_id],
            "profile_card": profile_cards.get(h_id, []),
            "rationale": rationales[h_id]
        }
        result_hypos.append(res_item)

        hypos_without.append({
            "id": h_id,
            "title": h.get("title", ""),
            "background_score": normalized_without_hist[h_id],
            "raw_prior": round(raw_priors_without_hist[h_id], 3)
        })

        hypos_with.append({
            "id": h_id,
            "title": h.get("title", ""),
            "background_score": normalized_with_hist[h_id],
            "raw_prior": round(raw_priors_with_hist[h_id], 3)
        })

    result_hypos.sort(key=lambda x: x["background_score"], reverse=True)

    return {
        "success": True,
        "hypotheses": result_hypos,
        "hypotheses_without_history": hypos_without,
        "hypotheses_with_history": hypos_with,
        "factor_weights": {
            "access": w_acc,
            "opportunity": w_opp,
            "means": w_means,
            "motive": w_mot,
            "travel_feasibility": w_travel
        },
        "include_criminal_history": include_history,
        "criminal_history_max_cap": max_history_cap,
        "legal_safeguard_notice": CRIMINAL_HISTORY_SAFEGUARD_NOTICE,
        "avoid_double_counting_rule": AVOID_DOUBLE_COUNTING_RULE,
        "sum_priors": 100.0
    }



