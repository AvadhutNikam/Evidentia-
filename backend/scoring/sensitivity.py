def compute_monte_carlo_scoring_ranges(
    hypotheses: List[Dict[str, Any]],
    exhibits: List[Dict[str, Any]],
    assessments: List[Dict[str, Any]],
    background_priors: Optional[Union[Dict[Any, float], List[Dict[str, Any]]]] = None,
    custom_lr_table: Optional[Dict[str, Dict[str, Any]]] = None,
    custom_base_configs: Optional[Dict[str, float]] = None,
    num_simulations: int = 250,
    random_seed: int = 42,
    excluded_exhibit_ids: Optional[List[Any]] = None
) -> Dict[str, Any]:
    """
    CHANGE 6: Monte Carlo Credible Ranges, "Cannot Separate" Results & Fragility Warnings
    =====================================================================================
    1. Runs Bayesian scoring N times (default 250 runs) sampling parameter uncertainty:
       - Likelihood ratios sampled in log-space across their empirical forensic ranges [min_lr, max_lr].
       - Exhibit source reliabilities sampled with Gaussian perturbation N(rel, 0.08) bounded to [0.10, 0.99].
       - Priors perturbed with log-normal noise and normalized to 100%.
    2. Reports each hypothesis as a credible low-to-high interval [p5, p95] alongside median, min, max, and std.
    3. Close Results Check:
       If the top two hypothesis ranges overlap substantially (or score difference <= 12%), flags
       cannot_separate = True, outputs plain wording:
       "evidence cannot clearly separate these suspects",
       and generates a list of discriminating evidence types that would resolve the tie.
    4. Fragility Check:
       Runs Leave-One-Out (LOO) sensitivity. If excluding a single exhibit flips Rank #1 or causes
       a >=15% drop in leading score, emits an explicit fragility warning naming the pivot exhibit.
    """
    if random_seed is not None:
        random.seed(random_seed)

    # 1. Baseline Run
    baseline_res = compute_bayesian_lr_scoring(
        hypotheses=hypotheses,
        exhibits=exhibits,
        assessments=assessments,
        background_priors=background_priors,
        custom_lr_table=custom_lr_table,
        custom_base_configs=custom_base_configs,
        excluded_exhibit_ids=excluded_exhibit_ids
    )

    if not baseline_res.get("success") or not baseline_res.get("hypotheses"):
        return {
            "success": False,
            "error": baseline_res.get("error", "Failed baseline Bayesian calculation"),
            "num_simulations": 0,
            "ranges": [],
            "cannot_separate": False,
            "close_results_warning": None,
            "discriminating_evidence_needed": [],
            "is_fragile": False,
            "fragile_exhibit_id": None,
            "fragile_exhibit_title": None,
            "fragility_message": None
        }

    baseline_hypos = baseline_res["hypotheses"]
    hypo_ids = [h["id"] for h in baseline_hypos]
    base_scores = {h["id"]: h["posterior_score"] for h in baseline_hypos}
    base_priors = {h["id"]: max(0.5, h.get("prior_score", 100.0 / len(hypo_ids))) for h in baseline_hypos}
    matrix = baseline_res.get("matrix", {})

    excluded_set = set(excluded_exhibit_ids or [])
    active_exhibits = [e for e in exhibits if e["id"] not in excluded_set]

    # Quick edge case: single hypothesis
    if len(hypo_ids) <= 1:
        h = baseline_hypos[0]
        single_range = {
            "hypothesis_id": h["id"],
            "title": h["title"],
            "is_unknown": h.get("is_unknown", False),
            "baseline_score": 100.0,
            "median_score": 100.0,
            "p5_score": 100.0,
            "p95_score": 100.0,
            "min_score": 100.0,
            "max_score": 100.0,
            "range_spread": 0.0,
            "std_dev": 0.0,
            "plain_label": "100.0% (Single hypothesis evaluated)"
        }
        return {
            "success": True,
            "num_simulations": 1,
            "ranges": [single_range],
            "cannot_separate": False,
            "close_results_warning": None,
            "discriminating_evidence_needed": [],
            "is_fragile": False,
            "fragile_exhibit_id": None,
            "fragile_exhibit_title": None,
            "fragility_message": None
        }

    # Extract sampling parameter configs per cell
    cell_sampling_configs = {}
    for ev in active_exhibits:
        ev_id = ev["id"]
        cell_sampling_configs[ev_id] = {}
        for h_id in hypo_ids:
            cell = matrix.get(ev_id, {}).get(h_id, {})
            b_lr = max(1e-9, float(cell.get("base_lr", cell.get("effective_lr", 1.0))))
            m_lr = max(1e-9, float(cell.get("min_lr", b_lr)))
            mx_lr = max(1e-9, float(cell.get("max_lr", b_lr)))
            if m_lr > mx_lr:
                m_lr, mx_lr = mx_lr, m_lr
            # If bounds are identical, inject a ±25% natural forensic uncertainty interval
            if abs(mx_lr - m_lr) < 1e-4:
                m_lr = max(1e-9, b_lr * 0.75)
                mx_lr = b_lr * 1.35

            w_dep = float(cell.get("dependency_weight_multiplier", 1.0))
            rel = float(cell.get("reliability", 0.85))

            cell_sampling_configs[ev_id][h_id] = {
                "min_lr": m_lr,
                "max_lr": mx_lr,
                "log_min": math.log(m_lr),
                "log_max": math.log(mx_lr),
                "w_dep": w_dep,
                "base_rel": rel
            }

    # 2. Run Monte Carlo Simulations
    simulated_scores = {h_id: [] for h_id in hypo_ids}

    for sim_idx in range(num_simulations):
        # 2a. Sample perturbed prior P(H_k)
        sample_log_priors = {}
        for h_id in hypo_ids:
            noise = random.gauss(0.0, 0.20)
            sample_log_priors[h_id] = math.log(max(1e-4, base_priors[h_id])) + noise

        max_log_pr = max(sample_log_priors.values())
        exp_pr = {h_id: math.exp(v - max_log_pr) for h_id, v in sample_log_priors.items()}
        sum_pr = sum(exp_pr.values()) or 1.0
        norm_priors = {h_id: exp_pr[h_id] / sum_pr for h_id in hypo_ids}

        # 2b. Sample reliabilities and likelihood ratios for each exhibit
        sim_log_posteriors = {h_id: math.log(norm_priors[h_id]) for h_id in hypo_ids}

        for ev in active_exhibits:
            ev_id = ev["id"]
            first_hid = hypo_ids[0]
            base_rel = cell_sampling_configs[ev_id][first_hid]["base_rel"]
            sampled_rel = max(0.10, min(0.99, random.gauss(base_rel, 0.08)))

            for h_id in hypo_ids:
                cfg = cell_sampling_configs[ev_id][h_id]
                sampled_log_lr = random.uniform(cfg["log_min"], cfg["log_max"])
                sampled_lr = math.exp(sampled_log_lr)

                # Shrink by sampled reliability
                if sampled_lr >= 1.0:
                    eff_lr = 1.0 + sampled_rel * (sampled_lr - 1.0)
                else:
                    eff_lr = math.exp(sampled_rel * math.log(max(1e-9, sampled_lr)))

                # Apply dependency group multiplier
                damped_lr = eff_lr ** cfg["w_dep"]
                sim_log_posteriors[h_id] += math.log(max(1e-9, damped_lr))

        # 2c. Softmax normalization across hypotheses
        max_log = max(sim_log_posteriors.values())
        exp_w = {h_id: math.exp(v - max_log) for h_id, v in sim_log_posteriors.items()}
        sum_exp = sum(exp_w.values()) or 1.0
        for h_id in hypo_ids:
            simulated_scores[h_id].append((exp_w[h_id] / sum_exp) * 100.0)

    # 3. Compute Percentiles & Summary Statistics
    range_results = []
    for h in baseline_hypos:
        h_id = h["id"]
        vals = sorted(simulated_scores[h_id])
        n_vals = len(vals)
        p5 = round(vals[max(0, int(0.05 * n_vals))], 1)
        p50 = round(vals[int(0.50 * n_vals)], 1)
        p95 = round(vals[min(n_vals - 1, int(0.95 * n_vals))], 1)
        min_s = round(vals[0], 1)
        max_s = round(vals[-1], 1)
        mean_s = round(sum(vals) / n_vals, 1)
        std_s = round(math.sqrt(sum((x - mean_s) ** 2 for x in vals) / n_vals), 1)
        b_s = base_scores.get(h_id, 0.0)
        spread = round(p95 - p5, 1)

        range_results.append({
            "hypothesis_id": h_id,
            "title": h["title"],
            "is_unknown": h.get("is_unknown", False),
            "baseline_score": b_s,
            "median_score": p50,
            "p5_score": p5,
            "p95_score": p95,
            "min_score": min_s,
            "max_score": max_s,
            "range_spread": spread,
            "std_dev": std_s,
            "plain_label": f"{b_s:.1f}% (range: {p5:.1f}% to {p95:.1f}%)"
        })

    # Sort ranges by baseline score descending
    range_results.sort(key=lambda x: x["baseline_score"], reverse=True)

    # 4. Close Results Detection ("Evidence cannot clearly separate these suspects")
    cannot_separate = False
    close_results_warning = None
    discriminating_evidence_needed = []

    if len(range_results) >= 2:
        top1 = range_results[0]
        top2 = range_results[1]

        overlap_low = max(top1["p5_score"], top2["p5_score"])
        overlap_high = min(top1["p95_score"], top2["p95_score"])
        has_overlap = (overlap_high >= overlap_low)
        score_diff = abs(top1["baseline_score"] - top2["baseline_score"])

        if has_overlap or score_diff <= 12.0:
            cannot_separate = True
            close_results_warning = f"Evidence cannot clearly separate these suspects: '{top1['title']}' ({top1['baseline_score']}%) and '{top2['title']}' ({top2['baseline_score']}%) have overlapping credible uncertainty ranges ({top1['p5_score']}% to {top1['p95_score']}% vs {top2['p5_score']}% to {top2['p95_score']}%)."

            # 1. Existing exhibits where diagnosticity ratio between Top 1 and Top 2 is near 1.0
            for ev in active_exhibits:
                ev_id = ev["id"]
                lr1 = matrix.get(ev_id, {}).get(top1["hypothesis_id"], {}).get("effective_lr", 1.0)
                lr2 = matrix.get(ev_id, {}).get(top2["hypothesis_id"], {}).get("effective_lr", 1.0)
                ratio_lr = max(lr1, lr2) / max(1e-9, min(lr1, lr2))
                if ratio_lr <= 1.8:
                    ev_title = ev.get("title") or ev.get("file_name", f"Exhibit #{ev_id}")
                    discriminating_evidence_needed.append(
                        f"Re-examination of Exhibit #{ev_id} ('{ev_title}'): Equally consistent with both suspects (ratio {ratio_lr:.2f}); forensic enhancement or higher-resolution analysis could discriminate."
                    )
                if len(discriminating_evidence_needed) >= 2:
                    break

            # 2. Add high-diagnosticity forensic steps that provide decisive separation
            standard_discriminators = [
                "DNA STR Comparison: Full autosomal profile matching or exclusion against crime scene biological trace.",
                "CCTV Facial Biometric Recovery: Uncompressed surveillance capture along primary egress corridor.",
                "Cell Tower CDR & Handset Telemetry: Simultaneous call records and subscriber location triangulation.",
                "Latent Friction Ridge Examination: ACE-V fingerprint comparison from physical entry latch.",
                "Independent Non-Party Alibi Corroboration: Official employer records, FASTag toll logs, or bank transactions."
            ]
            for disc in standard_discriminators:
                if len(discriminating_evidence_needed) < 4:
                    discriminating_evidence_needed.append(disc)

    # 5. Fragility Warning (Leave-One-Out Analysis)
    is_fragile = False
    fragile_exhibit_id = None
    fragile_exhibit_title = None
    fragility_message = None

    loo_res = calculate_sensitivity_and_robustness(
        hypotheses=hypotheses,
        exhibits=exhibits,
        assessments=assessments,
        custom_base_configs=custom_base_configs
    )

    if loo_res.get("success") and loo_res.get("critical_exhibits"):
        crit = loo_res["critical_exhibits"][0]
        is_fragile = True
        fragile_exhibit_id = crit["evidence_id"]
        fragile_exhibit_title = crit["evidence_title"]
        top_h_title = range_results[0]["title"]
        if crit.get("rank_flipped"):
            fragility_message = f"Result is fragile: Exhibit '{crit['evidence_title']}' heavily carries the result. If this single exhibit is excluded or discredited, the leading ranking flips to an alternate suspect."
        else:
            fragility_message = f"Result is fragile: Exhibit '{crit['evidence_title']}' heavily carries the result. If this exhibit is excluded, the leading suspect '{top_h_title}' score drops sharply by {crit['max_score_delta']} percentage points."

    return {
        "success": True,
        "num_simulations": num_simulations,
        "ranges": range_results,
        "cannot_separate": cannot_separate,
        "close_results_warning": close_results_warning,
        "discriminating_evidence_needed": discriminating_evidence_needed,
        "is_fragile": is_fragile,
        "fragile_exhibit_id": fragile_exhibit_id,
        "fragile_exhibit_title": fragile_exhibit_title,
        "fragility_message": fragility_message
    }


