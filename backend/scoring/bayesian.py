def combine_scores_bayesian(
    evidence_scores: Union[Dict[Any, float], List[Dict[str, Any]]],
    background_scores: Union[Dict[Any, float], List[Dict[str, Any]]],
    evidence_weight: float = 1.0
) -> Dict[str, Any]:
    """
    Computes Combined Priority: 'Combined investigative priority'
    Merges Evidence Relative Support (Likelihood) and Background Plausibility (Prior)
    via Bayesian updating:
      Posterior_i = (Likelihood_i ^ w) * Prior_i / Normalizer
    
    Independent function: does NOT call evidence scoring or background scoring internals.
    """
    ev_map = {}
    if isinstance(evidence_scores, dict):
        ev_map = evidence_scores
    elif isinstance(evidence_scores, list):
        for item in evidence_scores:
            val = item.get("evidence_score", item.get("support_score", item.get("relative_likelihood", 50.0)))
            ev_map[item["id"]] = float(val)

    bg_map = {}
    if isinstance(background_scores, dict):
        bg_map = background_scores
    elif isinstance(background_scores, list):
        for item in background_scores:
            val = item.get("background_score", item.get("raw_prior", 50.0))
            bg_map[item["id"]] = float(val)

    all_ids = list(dict.fromkeys(list(ev_map.keys()) + list(bg_map.keys())))
    if not all_ids:
        return {"success": False, "hypotheses": [], "evidence_weight": evidence_weight}

    unnormalized_posteriors = {}
    for h_id in all_ids:
        p_prior = max(1e-4, bg_map.get(h_id, 100.0 / len(all_ids)) / 100.0)
        p_ev = max(1e-4, ev_map.get(h_id, 100.0 / len(all_ids)) / 100.0)
        unnorm = (p_ev ** max(0.1, evidence_weight)) * p_prior
        unnormalized_posteriors[h_id] = unnorm

    sum_posteriors = sum(unnormalized_posteriors.values())
    if sum_posteriors <= 1e-9:
        normalized_combined = {h_id: round(100.0 / len(all_ids), 1) for h_id in all_ids}
    else:
        normalized_combined = {
            h_id: round((unnorm / sum_posteriors) * 100.0, 1)
            for h_id, unnorm in unnormalized_posteriors.items()
        }

    curr_sum = round(sum(normalized_combined.values()), 1)
    diff = round(100.0 - curr_sum, 1)
    if abs(diff) > 0.001 and len(normalized_combined) > 0:
        top_h = max(normalized_combined.items(), key=lambda x: x[1])[0]
        normalized_combined[top_h] = round(normalized_combined[top_h] + diff, 1)

    results = []
    for h_id in all_ids:
        bg_val = round(bg_map.get(h_id, 0.0), 1)
        ev_val = round(ev_map.get(h_id, 0.0), 1)
        comb_val = normalized_combined[h_id]

        bf = round(comb_val / max(0.1, bg_val), 2)
        shift_delta = round(comb_val - bg_val, 1)
        if shift_delta >= 1.5:
            shift_dir = "increased"
        elif shift_delta <= -1.5:
            shift_dir = "decreased"
        else:
            shift_dir = "stable"

        results.append({
            "id": h_id,
            "evidence_score": ev_val,
            "background_score": bg_val,
            "combined_score": comb_val,
            "bayes_factor": bf,
            "shift_direction": shift_dir,
            "shift_delta": shift_delta
        })

    results.sort(key=lambda x: x["combined_score"], reverse=True)

    return {
        "success": True,
        "hypotheses": results,
        "evidence_weight": evidence_weight
    }



def compute_bayesian_lr_scoring(
    hypotheses: List[Dict[str, Any]],
    exhibits: List[Dict[str, Any]],
    assessments: List[Dict[str, Any]],
    background_priors: Optional[Union[Dict[Any, float], List[Dict[str, Any]]]] = None,
    custom_lr_table: Optional[Dict[str, Dict[str, Any]]] = None,
    custom_base_configs: Optional[Dict[str, float]] = None,
    lr_mode: str = "typical",  # "typical", "conservative", "aggressive"
    excluded_exhibit_ids: Optional[List[Any]] = None
) -> Dict[str, Any]:
    """
    CHANGE 4: Bayesian Updating with Likelihood Ratios
    ==================================================
    Replaces hand-picked rating weights with an exact probabilistic method:
      1. Starts from the prior distribution P(H_k) (from background plausibility or uniform 1/K).
      2. For each exhibit, estimates: how likely would we see this evidence if hypothesis A were true,
         compared with if hypothesis B were true? That ratio is the likelihood ratio from the Reference Table.
      3. Shrinks each ratio toward 1.0 based on exhibit reliability and AI confidence.
      4. Multiplies by each exhibit's ratio:
           Unnormalized P(H_k | Exhibits) = P(H_k) * Prod_{i=1}^N LR_i(H_k)
      5. Normalizes so the results sum strictly to 100.0%.

    Key Scientific Guarantees:
      - Percentages sum to 100.0%.
      - Irrelevant evidence (LR = 1.0) changes nothing.
      - Strong exculpatory evidence sharply reduces a suspect.
      - Results don't depend on the order the exhibits are added (commutative multiplication).
      - Diagnosticity comes out naturally: evidence equally likely under all hypotheses has a ratio of 1 and no effect.
    """
    excluded_set = set(excluded_exhibit_ids or [])
    active_exhibits = [e for e in exhibits if e["id"] not in excluded_set]
    hypo_ids = [h["id"] for h in hypotheses]

    # Quick Edge Case: No hypotheses
    if not hypotheses:
        return {
            "success": False,
            "error": "No hypotheses provided for Bayesian evaluation.",
            "hypotheses": [],
            "matrix": {},
            "total_posterior_sum": 0.0,
            "order_independence_verified": True
        }

    # Quick Edge Case: Single hypothesis
    if len(hypotheses) == 1:
        h = hypotheses[0]
        return {
            "success": True,
            "edge_case": "single_hypothesis",
            "message": "Only one hypothesis evaluated; posterior is 100.0% by definition.",
            "total_posterior_sum": 100.0,
            "order_independence_verified": True,
            "hypotheses": [{
                "id": h["id"],
                "title": h.get("title", ""),
                "description": h.get("description", ""),
                "prior_score": 100.0,
                "posterior_score": 100.0,
                "evidence_score": 100.0,
                "combined_score": 100.0,
                "cumulative_lr": 1.0,
                "log10_cumulative_lr": 0.0,
                "credibility_interval": [100.0, 100.0],
                "status": "Primary Candidate"
            }],
            "matrix": {},
            "pairwise_likelihood_ratios": {},
            "exhibit_diagnosticity": {}
        }

    # Step 1: Extract & Normalize Prior Probabilities P(H_k)
    priors_raw = {}
    if background_priors is not None:
        if isinstance(background_priors, dict):
            priors_raw = {h_id: float(background_priors.get(h_id, 100.0 / len(hypo_ids))) for h_id in hypo_ids}
        elif isinstance(background_priors, list):
            for item in background_priors:
                val = item.get("background_score", item.get("raw_prior", 100.0 / len(hypo_ids)))
                priors_raw[item["id"]] = float(val)
    
    # Fill missing priors with equal split
    for h_id in hypo_ids:
        if h_id not in priors_raw or priors_raw[h_id] <= 0:
            priors_raw[h_id] = 100.0 / len(hypo_ids)

    sum_raw_prior = sum(priors_raw.values()) or 1.0
    priors_norm = {h_id: priors_raw[h_id] / sum_raw_prior for h_id in hypo_ids}
    priors_pct = {h_id: round(priors_norm[h_id] * 100.0, 1) for h_id in hypo_ids}

    # Step 2: Build Matrix & Resolve Reliabilities & Dependency Multipliers
    assessment_map = {(a["evidence_id"], a["hypothesis_id"]): a for a in assessments}
    exhibit_multipliers, group_audits = resolve_exhibit_dependency_multipliers(active_exhibits)

    unknown_ids = {
        h["id"] for h in hypotheses
        if bool(h.get("is_unknown") or h.get("title") == UNKNOWN_HYPOTHESIS_TITLE or (h.get("title") and "unknown" in h["title"].lower()))
    }
    named_ids = [hid for hid in hypo_ids if hid not in unknown_ids]

    exhibit_reliability = {}
    reliability_audits = {}
    for ev in active_exhibits:
        rel_val, audit = resolve_exhibit_reliability(ev, custom_base_configs)
        exhibit_reliability[ev["id"]] = rel_val
        reliability_audits[ev["id"]] = audit

    # Step 3: Resolve Likelihood Ratios per Cell with Clearing Factors & Dependency Damping
    detailed_matrix = {}
    cell_audits_by_hypo = {h_id: [] for h_id in hypo_ids}
    cell_lrs_for_reverse_check = {h_id: [] for h_id in hypo_ids}

    for ev in active_exhibits:
        ev_id = ev["id"]
        ev_type = ev.get("evidence_type", "document")
        rel = exhibit_reliability[ev_id]
        w_dep = exhibit_multipliers.get(ev_id, 1.0)
        detailed_matrix[ev_id] = {}

        # 3a. First resolve named hypotheses
        named_audits_for_ev = []
        for h_id in named_ids:
            cell = assessment_map.get((ev_id, h_id))
            lr_audit = resolve_assessment_likelihood_ratio(
                assessment=cell,
                evidence_type=ev_type,
                reliability=rel,
                lr_mode=lr_mode,
                custom_table=custom_lr_table
            )
            # Clearing status for named suspect
            clearing_res = evaluate_assessment_clearing_status(
                finding_category=lr_audit.get("finding_category"),
                classification=cell.get("classification") if cell else None,
                effective_lr=lr_audit["effective_lr"],
                reliability=rel
            )
            lr_audit["is_exculpatory"] = clearing_res["is_exculpatory"]
            lr_audit["clearing_factor_note"] = clearing_res["clearing_note"]
            lr_audit["clearing_level"] = clearing_res["clearing_level"]
            lr_audit["clearing_type"] = clearing_res["clearing_type"]
            lr_audit["statutory_reference"] = clearing_res.get("statutory_reference")

            lr_audit["evidence_id"] = ev_id
            lr_audit["evidence_title"] = ev.get("title") or ev.get("file_name", f"Exhibit #{ev_id}")
            lr_audit["hypothesis_id"] = h_id
            lr_audit["quoted_source_line"] = cell.get("quoted_source_line", "") if cell else ""
            lr_audit["reason"] = cell.get("reason", "") if cell else ""
            lr_audit["analyst_override"] = bool(cell.get("analyst_override", False)) if cell else False

            detailed_matrix[ev_id][h_id] = lr_audit
            named_audits_for_ev.append(lr_audit)

        # 3b. Resolve unknown hypotheses (Open-World Hypothesis Dynamics)
        for u_id in unknown_ids:
            cell = assessment_map.get((ev_id, u_id))
            if cell and (cell.get("finding_category") or cell.get("classification")):
                # Explicit assessment provided
                lr_audit = resolve_assessment_likelihood_ratio(
                    assessment=cell,
                    evidence_type=ev_type,
                    reliability=rel,
                    lr_mode=lr_mode,
                    custom_table=custom_lr_table
                )
                lr_audit["reason"] = cell.get("reason", "")
                clearing_res = evaluate_assessment_clearing_status(
                    finding_category=lr_audit.get("finding_category"),
                    classification=cell.get("classification") if cell else None,
                    effective_lr=lr_audit["effective_lr"],
                    reliability=rel
                )
                lr_audit["is_exculpatory"] = clearing_res["is_exculpatory"]
                lr_audit["clearing_factor_note"] = clearing_res["clearing_note"]
                lr_audit["clearing_level"] = clearing_res["clearing_level"]
                lr_audit["clearing_type"] = clearing_res["clearing_type"]
            else:
                # Deduce Unknown hypothesis reaction from evidence fit across named suspects
                has_cleared_named = any(a.get("is_exculpatory") or a.get("effective_lr", 1.0) < 0.25 for a in named_audits_for_ev)
                all_cleared_named = bool(named_audits_for_ev) and all(a.get("is_exculpatory") or a.get("effective_lr", 1.0) < 0.25 for a in named_audits_for_ev)
                max_named_lr = max([a.get("effective_lr", 1.0) for a in named_audits_for_ev] + [1.0])

                if all_cleared_named:
                    # Decisively clears all listed suspects -> strongly corroborates unlisted perpetrator
                    u_eff = 3.0
                    u_min = 2.0
                    u_max = 5.0
                    u_reason = "Exhibit refutes all listed suspects; corroborates unlisted perpetrator."
                    u_dir = "supports"
                elif has_cleared_named and max_named_lr < 2.0:
                    u_eff = 1.3
                    u_min = 1.1
                    u_max = 1.6
                    u_reason = "Exhibit clears listed suspect(s) without identifying an alternate listed suspect."
                    u_dir = "supports"
                elif max_named_lr >= 10.0:
                    # Decisive match to a specific named suspect -> actively discounts unlisted perpetrator
                    inv_lr = max(0.005, min(1.0, 1.0 / math.sqrt(max_named_lr)))
                    u_eff = inv_lr
                    u_min = max(0.001, inv_lr * 0.5)
                    u_max = min(1.0, inv_lr * 1.5)
                    u_reason = f"Exhibit strongly inculpates a specific named suspect (LR: {max_named_lr:.1f}x), disconfirming unlisted perpetrator."
                    u_dir = "exculpates"
                else:
                    u_eff = 1.0
                    u_min = 1.0
                    u_max = 1.0
                    u_reason = "Neutral exhibit; consistent with alternative explanation."
                    u_dir = "neutral"

                lr_audit = {
                    "finding_category": "general_irrelevant_neutral",
                    "finding_name": "Open-World Investigative Assessment",
                    "finding_description": "Probabilistic assessment for unlisted/alternative perpetrator.",
                    "support_direction": u_dir,
                    "base_lr": u_eff,
                    "effective_lr": u_eff,
                    "min_lr": u_min,
                    "max_lr": u_max,
                    "effective_min_lr": u_min,
                    "effective_max_lr": u_max,
                    "confidence": 0.85,
                    "reliability": rel,
                    "shrinkage_factor_alpha": 1.0,
                    "weight_of_evidence_bans": round(10.0 * math.log10(max(1e-9, u_eff)), 2),
                    "source_citation": "Open-World Bayesian Evidence Model",
                    "forensic_error_rate": "N/A",
                    "notes": u_reason,
                    "is_exculpatory": False,
                    "clearing_factor_note": None,
                    "clearing_level": "none",
                    "clearing_type": None,
                    "reason": u_reason
                }

            lr_audit["evidence_id"] = ev_id
            lr_audit["evidence_title"] = ev.get("title") or ev.get("file_name", f"Exhibit #{ev_id}")
            lr_audit["hypothesis_id"] = u_id
            lr_audit["quoted_source_line"] = cell.get("quoted_source_line", "") if cell else ""
            lr_audit["analyst_override"] = bool(cell.get("analyst_override", False)) if cell else False
            detailed_matrix[ev_id][u_id] = lr_audit

        # 3c. Apply dependency damping to all hypotheses for this exhibit
        for h_id in hypo_ids:
            audit = detailed_matrix[ev_id][h_id]
            eff_lr = max(1e-9, audit["effective_lr"])
            damped_log = w_dep * math.log(eff_lr)
            damped_lr = math.exp(damped_log)

            audit["dependency_group"] = ev.get("dependency_group")
            audit["dependency_weight_multiplier"] = w_dep
            audit["damped_likelihood_ratio"] = round(damped_lr, 6)
            audit["effective_lr_damped"] = round(damped_lr, 6)
            audit["weight_of_evidence_bans"] = round(w_dep * audit.get("weight_of_evidence_bans", 0.0), 2)

            cell_audits_by_hypo[h_id].append(audit)
            cell_lrs_for_reverse_check[h_id].append(damped_lr)

    # Step 4: Cumulative Log-Likelihood Calculation (Numerically Stable with Damped LRs)
    log_posteriors = {}
    log_ev_only = {}
    log_post_min = {}
    log_post_max = {}
    cum_lrs = {}

    for h_id in hypo_ids:
        prior_p = max(1e-9, priors_norm[h_id])
        log_prior = math.log(prior_p)
        log_uniform = math.log(1.0 / len(hypo_ids))

        sum_log_lr = 0.0
        sum_log_min = 0.0
        sum_log_max = 0.0

        for audit in cell_audits_by_hypo[h_id]:
            damped_lr = max(1e-9, audit["damped_likelihood_ratio"])
            eff_min = max(1e-9, audit["effective_min_lr"])
            eff_max = max(1e-9, audit["effective_max_lr"])
            w = audit.get("dependency_weight_multiplier", 1.0)

            sum_log_lr += math.log(damped_lr)
            sum_log_min += w * math.log(eff_min)
            sum_log_max += w * math.log(eff_max)

        log_posteriors[h_id] = log_prior + sum_log_lr
        log_ev_only[h_id] = log_uniform + sum_log_lr
        log_post_min[h_id] = log_prior + sum_log_min
        log_post_max[h_id] = log_prior + sum_log_max
        cum_lrs[h_id] = math.exp(min(50.0, max(-50.0, sum_log_lr)))

    # Step 5: Safe Normalization via Softmax / LogSumExp
    def _normalize_log_scores(log_scores: Dict[Any, float]) -> Dict[Any, float]:
        if not log_scores:
            return {}
        max_log = max(log_scores.values())
        exp_weights = {k: math.exp(v - max_log) for k, v in log_scores.items()}
        sum_exp = sum(exp_weights.values()) or 1.0
        raw_pcts = {k: (w / sum_exp) * 100.0 for k, w in exp_weights.items()}

        rounded = {k: round(v, 1) for k, v in raw_pcts.items()}
        curr_sum = round(sum(rounded.values()), 1)
        diff = round(100.0 - curr_sum, 1)
        if abs(diff) > 0.001 and len(rounded) > 0:
            top_k = max(rounded.items(), key=lambda x: x[1])[0]
            rounded[top_k] = round(rounded[top_k] + diff, 1)
        return rounded

    normalized_posteriors = _normalize_log_scores(log_posteriors)
    normalized_ev_only = _normalize_log_scores(log_ev_only)
    normalized_min = _normalize_log_scores(log_post_min)
    normalized_max = _normalize_log_scores(log_post_max)

    # Step 6: Order-Independence Verification
    # Assert multiplication order does not affect final log likelihoods
    order_independence_verified = True
    for h_id in hypo_ids:
        forward_sum = sum(math.log(max(1e-9, lr)) for lr in cell_lrs_for_reverse_check[h_id])
        reverse_sum = sum(math.log(max(1e-9, lr)) for lr in reversed(cell_lrs_for_reverse_check[h_id]))
        if abs(forward_sum - reverse_sum) > 1e-5:
            order_independence_verified = False

    # Step 7: Natural Diagnosticity per Exhibit
    # Diagnosticity Ratio: max(LR_i) / min(LR_i). If ratio is 1.0, exhibit separates nothing.
    exhibit_diagnosticity = {}
    for ev in active_exhibits:
        ev_id = ev["id"]
        lrs_for_ev = [detailed_matrix[ev_id][h_id]["effective_lr"] for h_id in hypo_ids]
        max_lr = max(lrs_for_ev)
        min_lr = max(1e-9, min(lrs_for_ev))
        diag_ratio = max_lr / min_lr

        if diag_ratio <= 1.05:
            cat = "Zero (Equally Likely across Hypotheses)"
            note = "Exhibit is equally consistent with all hypotheses; ratio is 1.0 and produces 0.0% probability change."
        elif diag_ratio <= 5.0:
            cat = "Low Diagnosticity"
            note = "Exhibit provides slight discrimination between competing theories."
        elif diag_ratio <= 50.0:
            cat = "Moderate Diagnosticity"
            note = "Exhibit substantially distinguishes primary hypothesis from competitors."
        else:
            cat = "High Diagnosticity"
            note = "Exhibit provides decisive separation between hypotheses."

        exhibit_diagnosticity[ev_id] = {
            "evidence_id": ev_id,
            "evidence_title": ev.get("title") or ev.get("file_name", f"Exhibit #{ev_id}"),
            "evidence_type": reliability_audits[ev_id]["evidence_type"],
            "diagnosticity_ratio": round(diag_ratio, 2),
            "category": cat,
            "note": note,
            "is_zero_diagnosticity": (diag_ratio <= 1.05)
        }

    # Step 8: Pairwise Likelihood Ratios (How much more likely under A than B)
    pairwise_lrs = {}
    for ev in active_exhibits:
        ev_id = ev["id"]
        pairwise_lrs[ev_id] = {}
        for h_a in hypo_ids:
            lr_a = detailed_matrix[ev_id][h_a]["effective_lr"]
            pairwise_lrs[ev_id][h_a] = {}
            for h_b in hypo_ids:
                if h_a != h_b:
                    lr_b = detailed_matrix[ev_id][h_b]["effective_lr"]
                    ratio_ab = round(lr_a / max(1e-9, lr_b), 3)
                    pairwise_lrs[ev_id][h_a][h_b] = ratio_ab

    # Step 9: Assemble Result Hypotheses
    result_hypotheses = []
    for h in hypotheses:
        h_id = h["id"]
        post_pct = normalized_posteriors[h_id]
        ev_pct = normalized_ev_only[h_id]
        prior_pct = priors_pct[h_id]
        c_min = min(normalized_min[h_id], normalized_max[h_id])
        c_max = max(normalized_min[h_id], normalized_max[h_id])
        is_un = (h_id in unknown_ids)

        status = "Active"
        if post_pct < 2.0:
            status = "Discarded"
        elif post_pct >= 65.0:
            status = "Primary Candidate"

        shift_delta = round(post_pct - prior_pct, 1)
        shift_dir = "increased" if shift_delta >= 1.5 else ("decreased" if shift_delta <= -1.5 else "stable")
        cum_lr = round(cum_lrs[h_id], 2)
        log10_cum_lr = round(math.log10(max(1e-9, cum_lrs[h_id])), 2)

        result_hypotheses.append({
            "id": h_id,
            "title": h.get("title", ""),
            "description": h.get("description", ""),
            "is_unknown": is_un,
            # Change 4 Probabilistic Numbers
            "posterior_score": post_pct,
            "prior_score": prior_pct,
            "evidence_score": ev_pct,
            "combined_score": post_pct,
            "cumulative_lr": cum_lr,
            "log10_cumulative_lr": log10_cum_lr,
            "bayes_factor": round(post_pct / max(0.1, prior_pct), 2),
            "credibility_interval": [c_min, c_max],
            "shift_delta": shift_delta,
            "shift_direction": shift_dir,
            "status": status,
            "assessments_count": len(cell_audits_by_hypo[h_id])
        })

    result_hypotheses.sort(key=lambda x: x["posterior_score"], reverse=True)

    lead_message = None
    if result_hypotheses and result_hypotheses[0].get("is_unknown"):
        lead_message = "The evidence does not clearly point to any listed suspect."
        result_hypotheses[0]["lead_message"] = lead_message

    return {
        "success": True,
        "scoring_method": "bayesian_likelihood_ratios",
        "lr_mode": lr_mode,
        "lead_message": lead_message,
        "total_posterior_sum": 100.0,
        "order_independence_verified": order_independence_verified,
        "hypotheses": result_hypotheses,
        "matrix": detailed_matrix,
        "dependency_groups_audit": group_audits,
        "pairwise_likelihood_ratios": pairwise_lrs,
        "exhibit_diagnosticity": exhibit_diagnosticity,
        "reliability_audits": reliability_audits,
        "reference_table_size": len(custom_lr_table or LIKELIHOOD_RATIO_REFERENCE_TABLE)
    }


def calculate_three_layer_ach_scoring(
    hypotheses: List[Dict[str, Any]],
    exhibits: List[Dict[str, Any]],
    assessments: List[Dict[str, Any]],
    custom_base_configs: Optional[Dict[str, float]] = None,
    excluded_exhibit_ids: Optional[List[Any]] = None,
    evidence_weight: float = 1.0,
    suspect_factors_by_hypothesis: Optional[Dict[Any, List[Dict[str, Any]]]] = None,
    background_config: Optional[Dict[str, Any]] = None,
    prior_records_by_hypothesis: Optional[Dict[Any, List[Dict[str, Any]]]] = None,
    current_case_profile: Optional[Dict[str, Any]] = None,
    scoring_method: str = "bayesian_lr",  # "bayesian_lr" (Change 4 default) or "classic_ach"
    lr_mode: str = "typical",
    custom_lr_table: Optional[Dict[str, Dict[str, Any]]] = None
) -> Dict[str, Any]:
    """
    Orchestrates Evidentia AI Scoring:
      1. Classic Richards Heuer ACH Scoring (Change 1 disconfirmation matrix baseline)
      2. Background Plausibility Priors (Change 2 & 3 profile factors + criminal history)
      3. Bayesian Updating with Likelihood Ratios (Change 4: prior * Prod(LR_i) normalized)
    """
    # Filter excluded exhibits
    excluded_set = set(excluded_exhibit_ids or [])
    active_exhibits = [e for e in exhibits if e["id"] not in excluded_set]

    # 1. Compute Classic Heuer ACH Evidence Scores (for comparison and validation)
    ev_res = compute_evidence_scores(
        hypotheses=hypotheses,
        exhibits=exhibits,
        assessments=assessments,
        custom_base_configs=custom_base_configs,
        excluded_exhibit_ids=excluded_exhibit_ids
    )

    # 2. Compute Background Plausibility Scores (Change 2 & 3)
    bg_res = compute_background_scores(
        hypotheses=hypotheses,
        suspect_factors_by_hypothesis=suspect_factors_by_hypothesis,
        background_config=background_config,
        prior_records_by_hypothesis=prior_records_by_hypothesis,
        current_case_profile=current_case_profile
    )

    # 3. Classic Combine via Heuer Exponential Decay
    comb_res_classic = combine_scores_bayesian(
        evidence_scores=ev_res.get("hypotheses", []),
        background_scores=bg_res.get("hypotheses", []),
        evidence_weight=evidence_weight
    )

    # 4. Change 4: Bayesian Updating with Likelihood Ratios
    # Run with Background Plausibility Priors
    bayesian_res = compute_bayesian_lr_scoring(
        hypotheses=hypotheses,
        exhibits=exhibits,
        assessments=assessments,
        background_priors=bg_res.get("hypotheses", []),
        custom_lr_table=custom_lr_table,
        custom_base_configs=custom_base_configs,
        lr_mode=lr_mode,
        excluded_exhibit_ids=excluded_exhibit_ids
    )

    # Run without Background Priors (Uniform 1/K) to get pure Evidence Score via Likelihood Ratios
    bayesian_ev_only_res = compute_bayesian_lr_scoring(
        hypotheses=hypotheses,
        exhibits=exhibits,
        assessments=assessments,
        background_priors=None,
        custom_lr_table=custom_lr_table,
        custom_base_configs=custom_base_configs,
        lr_mode=lr_mode,
        excluded_exhibit_ids=excluded_exhibit_ids
    )

    # Run without Criminal History for dual ranking
    bayesian_res_without_hist = compute_bayesian_lr_scoring(
        hypotheses=hypotheses,
        exhibits=exhibits,
        assessments=assessments,
        background_priors=bg_res.get("hypotheses_without_history", []),
        custom_lr_table=custom_lr_table,
        custom_base_configs=custom_base_configs,
        lr_mode=lr_mode,
        excluded_exhibit_ids=excluded_exhibit_ids
    )

    bayesian_res_with_hist = compute_bayesian_lr_scoring(
        hypotheses=hypotheses,
        exhibits=exhibits,
        assessments=assessments,
        background_priors=bg_res.get("hypotheses_with_history", []),
        custom_lr_table=custom_lr_table,
        custom_base_configs=custom_base_configs,
        lr_mode=lr_mode,
        excluded_exhibit_ids=excluded_exhibit_ids
    )

    # Map lookups
    classic_comb_map = {h["id"]: h for h in comb_res_classic.get("hypotheses", [])}
    classic_ev_map = {h["id"]: h for h in ev_res.get("hypotheses", [])}
    bg_map = {h["id"]: h for h in bg_res.get("hypotheses", [])}
    bayes_map = {h["id"]: h for h in bayesian_res.get("hypotheses", [])}
    bayes_ev_map = {h["id"]: h for h in bayesian_ev_only_res.get("hypotheses", [])}
    bayes_without_map = {h["id"]: h for h in bayesian_res_without_hist.get("hypotheses", [])}
    bayes_with_map = {h["id"]: h for h in bayesian_res_with_hist.get("hypotheses", [])}

    # Dual ranking (with vs without history)
    sorted_without = sorted(bayes_without_map.values(), key=lambda x: x["posterior_score"], reverse=True)
    rank_without_map = {h["id"]: idx + 1 for idx, h in enumerate(sorted_without)}

    sorted_with = sorted(bayes_with_map.values(), key=lambda x: x["posterior_score"], reverse=True)
    rank_with_map = {h["id"]: idx + 1 for idx, h in enumerate(sorted_with)}

    bg_without_map = {h["id"]: h["background_score"] for h in bg_res.get("hypotheses_without_history", [])}
    bg_with_map = {h["id"]: h["background_score"] for h in bg_res.get("hypotheses_with_history", [])}

    # Merge into unified hypothesis records
    unified_hypotheses = []
    for h in hypotheses:
        h_id = h["id"]
        b_h = bayes_map.get(h_id, {})
        b_ev = bayes_ev_map.get(h_id, {})
        c_h = classic_comb_map.get(h_id, {})
        c_ev = classic_ev_map.get(h_id, {})
        bg_h = bg_map.get(h_id, {})

        # Primary numbers: Bayesian Likelihood Ratio Updating
        bayesian_comb = b_h.get("posterior_score", 50.0)
        bayesian_ev = b_ev.get("posterior_score", 50.0)
        classic_comb = c_h.get("combined_score", 50.0)
        classic_ev = c_ev.get("evidence_score", 50.0)
        bg_score = bg_h.get("background_score", 50.0)
        penalty = c_ev.get("disconfirmation_penalty", 0.0)

        # Active score selected by method
        if scoring_method == "classic_ach":
            active_comb = classic_comb
            active_ev = classic_ev
        else:
            active_comb = bayesian_comb
            active_ev = bayesian_ev

        bg_without = bg_without_map.get(h_id, bg_score)
        bg_with = bg_with_map.get(h_id, bg_score)
        comb_without = bayes_without_map.get(h_id, {}).get("posterior_score", active_comb)
        comb_with = bayes_with_map.get(h_id, {}).get("posterior_score", active_comb)
        r_without = rank_without_map.get(h_id, 1)
        r_with = rank_with_map.get(h_id, 1)

        status = "Active"
        if penalty >= 10.0 and active_comb < 2.0:
            status = "Discarded"
        elif active_comb >= 65.0:
            status = "Primary Candidate"

        is_un = bool(h.get("is_unknown") or h.get("title") == UNKNOWN_HYPOTHESIS_TITLE or (h.get("title") and "unknown" in h["title"].lower()))
        scoring_inputs = {
            "evidence_score": active_ev,
            "background_score": bg_score,
            "combined_score": active_comb,
            "bayesian_lr_score": bayesian_comb,
            "bayesian_evidence_score": bayesian_ev,
            "classic_ach_score": classic_comb,
            "classic_evidence_score": classic_ev,
            "cumulative_lr": b_h.get("cumulative_lr", 1.0),
            "credibility_interval": b_h.get("credibility_interval", [bayesian_comb, bayesian_comb]),
            "background_score_without_history": bg_without,
            "background_score_with_history": bg_with,
            "combined_score_without_history": comb_without,
            "combined_score_with_history": comb_with,
            "history_contribution_pct": round(bg_with - bg_without, 1),
            "rank_with_history": r_with,
            "rank_without_history": r_without,
            "disconfirmation_penalty": penalty,
            "scoring_method": scoring_method,
            "is_unknown": is_un
        }

        unified_hypotheses.append({
            "id": h_id,
            "title": h.get("title", ""),
            "description": h.get("description", ""),
            "is_unknown": is_un,
            # Three-Layer numbers
            "evidence_score": active_ev,
            "background_score": bg_score,
            "combined_score": active_comb,
            # Dual method visibility (Change 4)
            "bayesian_lr_score": bayesian_comb,
            "bayesian_evidence_score": bayesian_ev,
            "classic_ach_score": classic_comb,
            "classic_evidence_score": classic_ev,
            "cumulative_lr": b_h.get("cumulative_lr", 1.0),
            "credibility_interval": b_h.get("credibility_interval", [bayesian_comb, bayesian_comb]),
            # History comparison (Change 3)
            "background_score_without_history": bg_without,
            "background_score_with_history": bg_with,
            "combined_score_without_history": comb_without,
            "combined_score_with_history": comb_with,
            "history_contribution": round(bg_with - bg_without, 1),
            "rank_with_history": r_with,
            "rank_without_history": r_without,
            "rank_changed": (r_with != r_without),
            # Backwards compatibility fields
            "support_score": active_comb,
            "relative_likelihood": active_ev,
            "disconfirmation_penalty": penalty,
            "status": status,
            # Breakdown factors
            "background_factors": bg_h.get("factors", {}),
            "background_profile_card": bg_h.get("profile_card", []),
            "background_rationale": bg_h.get("rationale", ""),
            "bayes_factor": b_h.get("bayes_factor", 1.0),
            "shift_direction": b_h.get("shift_direction", "stable"),
            "scoring_inputs": scoring_inputs
        })

    unified_hypotheses.sort(key=lambda x: x["combined_score"], reverse=True)

    lead_message = None
    if unified_hypotheses and unified_hypotheses[0].get("is_unknown"):
        lead_message = "The evidence does not clearly point to any listed suspect."
        unified_hypotheses[0]["lead_message"] = lead_message

    comparison_hypos = []
    for uh in unified_hypotheses:
        comparison_hypos.append({
            "hypothesis_id": uh["id"],
            "title": uh["title"],
            "is_unknown": uh.get("is_unknown", False),
            "lead_message": uh.get("lead_message"),
            "rank_with_history": uh["rank_with_history"],
            "rank_without_history": uh["rank_without_history"],
            "background_with_history": uh["background_score_with_history"],
            "background_without_history": uh["background_score_without_history"],
            "combined_with_history": uh["combined_score_with_history"],
            "combined_without_history": uh["combined_score_without_history"],
            "evidence_score": uh["evidence_score"],
            "bayesian_lr_score": uh["bayesian_lr_score"],
            "classic_ach_score": uh["classic_ach_score"],
            "history_contribution_pct": uh["history_contribution"],
            "rank_changed": uh["rank_changed"]
        })

    total_prior_recs = sum(len(recs) for recs in (prior_records_by_hypothesis or {}).values())

    criminal_history_comparison = {
        "include_criminal_history": bg_res.get("include_criminal_history", True),
        "criminal_history_max_cap": bg_res.get("criminal_history_max_cap", 0.10),
        "legal_safeguard_notice": CRIMINAL_HISTORY_SAFEGUARD_NOTICE,
        "total_prior_records": total_prior_recs,
        "hypotheses_comparison": comparison_hypos
    }

    # Combined matrix: merges classic ACH metrics with Bayesian LR metrics
    merged_matrix = {}
    classic_matrix = ev_res.get("matrix", {})
    bayes_matrix = bayesian_res.get("matrix", {})

    for ev in active_exhibits:
        ev_id = ev["id"]
        merged_matrix[ev_id] = {}
        for h in hypotheses:
            h_id = h["id"]
            c_cell = classic_matrix.get(ev_id, {}).get(h_id, {})
            b_cell = bayes_matrix.get(ev_id, {}).get(h_id, {})
            merged_matrix[ev_id][h_id] = {
                # Bayesian LR fields (Change 4)
                "finding_category": b_cell.get("finding_category", "general_irrelevant_neutral"),
                "finding_name": b_cell.get("finding_name", "General Exhibit"),
                "finding_description": b_cell.get("finding_description", ""),
                "effective_lr": b_cell.get("effective_lr", 1.0),
                "base_lr": b_cell.get("base_lr", 1.0),
                "min_lr": b_cell.get("min_lr", 1.0),
                "max_lr": b_cell.get("max_lr", 1.0),
                "shrinkage_factor_alpha": b_cell.get("shrinkage_factor_alpha", 1.0),
                "weight_of_evidence_bans": b_cell.get("weight_of_evidence_bans", 0.0),
                "source_citation": b_cell.get("source_citation", "Standard Forensic Guidelines"),
                "forensic_error_rate": b_cell.get("forensic_error_rate", "N/A"),
                # Change 5: Exculpatory & Dependency Group Fields
                "dependency_group": b_cell.get("dependency_group") or c_cell.get("dependency_group"),
                "dependency_weight_multiplier": b_cell.get("dependency_weight_multiplier", 1.0),
                "damped_likelihood_ratio": b_cell.get("damped_likelihood_ratio", b_cell.get("effective_lr", 1.0)),
                "is_exculpatory": b_cell.get("is_exculpatory", False),
                "clearing_factor_note": b_cell.get("clearing_factor_note"),
                "clearing_level": b_cell.get("clearing_level", "none"),
                "clearing_type": b_cell.get("clearing_type"),
                "statutory_reference": b_cell.get("statutory_reference"),
                # Classic ACH fields
                "classification": c_cell.get("classification", "neutral"),
                "classification_label": c_cell.get("classification_label", "Neutral"),
                "confidence": b_cell.get("confidence", c_cell.get("confidence", 0.85)),
                "reliability": b_cell.get("reliability", c_cell.get("reliability", 1.0)),
                "diagnosticity": c_cell.get("diagnosticity", 1.0),
                "cell_penalty": c_cell.get("cell_penalty", 0.0),
                "cell_bonus": c_cell.get("cell_bonus", 0.0),
                "contribution": c_cell.get("contribution", 0.0),
                "reason": b_cell.get("reason", c_cell.get("reason", "")),
                "quoted_source_line": b_cell.get("quoted_source_line", c_cell.get("quoted_source_line", "")),
                "analyst_override": b_cell.get("analyst_override", c_cell.get("analyst_override", False))
            }

    # Enrich hypothesis_breakdowns with Bayesian LR fields and cluster by dependency
    enriched_breakdowns = {}
    raw_breakdowns = ev_res.get("hypothesis_breakdowns", {})
    for h_id, rows in raw_breakdowns.items():
        enriched_rows = []
        for r in rows:
            ev_id = r.get("evidence_id")
            m_cell = merged_matrix.get(ev_id, {}).get(h_id, {})
            row_copy = dict(r)
            row_copy.update({
                "finding_category": m_cell.get("finding_category", "general_irrelevant_neutral"),
                "finding_name": m_cell.get("finding_name", "General Exhibit"),
                "effective_lr": m_cell.get("effective_lr", 1.0),
                "base_lr": m_cell.get("base_lr", 1.0),
                "min_lr": m_cell.get("min_lr", 1.0),
                "max_lr": m_cell.get("max_lr", 1.0),
                "weight_of_evidence_bans": m_cell.get("weight_of_evidence_bans", 0.0),
                "source_citation": m_cell.get("source_citation", "Standard Forensic Guidelines"),
                "forensic_error_rate": m_cell.get("forensic_error_rate", "N/A"),
                "shrinkage_factor_alpha": m_cell.get("shrinkage_factor_alpha", 1.0),
                # Change 5: Clearing Factor and Dependency Cluster Metadata
                "dependency_group": m_cell.get("dependency_group"),
                "dependency_weight_multiplier": m_cell.get("dependency_weight_multiplier", 1.0),
                "damped_likelihood_ratio": m_cell.get("damped_likelihood_ratio", 1.0),
                "is_exculpatory": m_cell.get("is_exculpatory", False),
                "clearing_factor_note": m_cell.get("clearing_factor_note"),
                "clearing_level": m_cell.get("clearing_level", "none"),
                "clearing_type": m_cell.get("clearing_type"),
                "statutory_reference": m_cell.get("statutory_reference")
            })
            enriched_rows.append(row_copy)
        # Cluster exhibits belonging to the same dependency group together
        enriched_breakdowns[h_id] = cluster_breakdown_rows_by_dependency(enriched_rows)

    return {
        "success": True,
        "scoring_method": scoring_method,
        "lr_mode": lr_mode,
        "lead_message": lead_message,
        "all_zero_diagnosticity": ev_res.get("all_zero_diagnosticity", False),
        "order_independence_verified": bayesian_res.get("order_independence_verified", True),
        "total_relative_sum": 100.0,
        "hypotheses": unified_hypotheses,
        "matrix": merged_matrix,
        "hypothesis_breakdowns": enriched_breakdowns,
        "dependency_groups_audit": bayesian_res.get("dependency_groups_audit", {}),
        "exculpatory_types_config": EXCULPATORY_EVIDENCE_TYPES_CONFIG,
        "reliability_audits": ev_res.get("reliability_audits", {}),
        "diagnosticity_audits": ev_res.get("diagnosticity_audits", {}),
        "bayesian_lr_audit": {
            "scoring_method": "bayesian_likelihood_ratios",
            "lr_mode": lr_mode,
            "order_independence_verified": bayesian_res.get("order_independence_verified", True),
            "pairwise_likelihood_ratios": bayesian_res.get("pairwise_likelihood_ratios", {}),
            "exhibit_diagnosticity": bayesian_res.get("exhibit_diagnosticity", {}),
            "total_posterior_sum": 100.0
        },
        "classic_ach_audit": {
            "scoring_method": "classic_heuer_ach",
            "decay_factor": 0.75,
            "support_bonus_factor": 0.20,
            "all_zero_diagnosticity": ev_res.get("all_zero_diagnosticity", False)
        },
        "background_summary": {
            "factor_weights": bg_res.get("factor_weights", {}),
            "sum_priors": bg_res.get("sum_priors", 100.0),
            "include_criminal_history": bg_res.get("include_criminal_history", True),
            "criminal_history_max_cap": bg_res.get("criminal_history_max_cap", 0.10),
            "legal_safeguard_notice": CRIMINAL_HISTORY_SAFEGUARD_NOTICE
        },
        "bayesian_summary": {
            "evidence_weight": evidence_weight
        },
        "criminal_history_comparison": criminal_history_comparison,
        "reference_table": LIKELIHOOD_RATIO_REFERENCE_TABLE
    }


def calculate_ach_scoring(
    hypotheses: List[Dict[str, Any]],
    exhibits: List[Dict[str, Any]],
    assessments: List[Dict[str, Any]],
    custom_base_configs: Optional[Dict[str, float]] = None,
    excluded_exhibit_ids: Optional[List[Any]] = None
) -> Dict[str, Any]:
    """
    Backwards-compatible wrapper delegating to calculate_three_layer_ach_scoring.
    Provides all three numbers alongside legacy matrix and sensitivity keys.
    """
    return calculate_three_layer_ach_scoring(
        hypotheses=hypotheses,
        exhibits=exhibits,
        assessments=assessments,
        custom_base_configs=custom_base_configs,
        excluded_exhibit_ids=excluded_exhibit_ids
    )

