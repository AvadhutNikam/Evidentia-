def shrink_likelihood_ratio(base_lr: float, reliability: float, confidence: float) -> Tuple[float, float]:
    """
    Shrinks the Likelihood Ratio toward 1.0 based on exhibit reliability and AI confidence.
    Power transformation: LR_effective = base_lr ^ (reliability * confidence)
    
    Mathematical Properties:
      - If alpha = 1.0 (perfect certainty and reliability): LR_effective = base_lr.
      - If alpha -> 0.0 (unreliable or uncertain evidence): LR_effective -> 1.0 (no effect).
      - If base_lr > 1.0: LR_effective shrinks downward toward 1.0.
      - If base_lr < 1.0: LR_effective shrinks upward toward 1.0.
      - If base_lr = 1.0: LR_effective = 1.0 (neutral remains neutral).
      - Preserves symmetric information weight: log(LR_effective) = alpha * log(base_lr).
    """
    r = max(0.05, min(0.99, float(reliability if reliability is not None else 1.0)))
    c = max(0.05, min(1.0, float(confidence if confidence is not None else 0.85)))
    alpha = max(0.02, min(1.0, r * c))

    if abs(base_lr - 1.0) < 1e-6:
        return 1.0, round(alpha, 3)

    # Safe power calculation
    try:
        shrunk = math.pow(base_lr, alpha)
        # Prevent numerical zero or extreme overflow
        shrunk = max(1e-7, min(1e9, shrunk))
        return round(shrunk, 6), round(alpha, 3)
    except Exception:
        return 1.0, round(alpha, 3)

def resolve_assessment_likelihood_ratio(
    assessment: Optional[Dict[str, Any]],
    evidence_type: str = "document",
    reliability: float = 1.0,
    lr_mode: str = "typical",
    custom_table: Optional[Dict[str, Dict[str, Any]]] = None
) -> Dict[str, Any]:
    """
    Resolves the grounded Likelihood Ratio for an evidence assessment.
    Uses the Reference Table as the definitive source of truth (AI does NOT invent the ratio).
    Shrinks the ratio toward 1 using reliability and confidence.
    """
    ref_table = custom_table or LIKELIHOOD_RATIO_REFERENCE_TABLE
    cell = assessment or {}
    
    # 1. Determine Category Key
    cat_key = cell.get("finding_category")
    if not cat_key or cat_key not in ref_table:
        cls_name = cell.get("classification") or "neutral"
        cat_key = map_legacy_classification_to_finding(cls_name, evidence_type)

    entry = ref_table.get(cat_key, ref_table["general_irrelevant_neutral"])

    # 2. Select Base LR according to lr_mode
    if lr_mode == "conservative":
        base_lr = float(entry["min_lr"])
    elif lr_mode == "aggressive":
        base_lr = float(entry["max_lr"])
    else:  # typical / standard
        base_lr = float(entry.get("typical_lr", math.sqrt(entry["min_lr"] * entry["max_lr"])))

    confidence = float(cell.get("llm_confidence") or cell.get("confidence") or 0.85)
    
    # 3. Shrink toward 1.0
    effective_lr, alpha = shrink_likelihood_ratio(base_lr, reliability, confidence)
    eff_min, _ = shrink_likelihood_ratio(float(entry["min_lr"]), reliability, confidence)
    eff_max, _ = shrink_likelihood_ratio(float(entry["max_lr"]), reliability, confidence)

    # Weight of evidence in decibans: 10 * log10(LR)
    log10_lr = math.log10(max(1e-9, effective_lr))
    weight_of_evidence_bans = round(10.0 * log10_lr, 2)

    return {
        "finding_category": cat_key,
        "finding_name": entry.get("finding_name", cat_key),
        "finding_description": entry.get("finding_description", entry.get("finding_name", "")),
        "support_direction": entry.get("support_direction", "supports"),
        "base_lr": base_lr,
        "effective_lr": effective_lr,
        "min_lr": float(entry.get("min_lr", 1.0)),
        "max_lr": float(entry.get("max_lr", 1.0)),
        "effective_min_lr": eff_min,
        "effective_max_lr": eff_max,
        "confidence": confidence,
        "reliability": reliability,
        "shrinkage_factor_alpha": alpha,
        "weight_of_evidence_bans": weight_of_evidence_bans,
        "source_citation": entry.get("source_citation", "Peer-reviewed forensic literature"),
        "forensic_error_rate": entry.get("forensic_error_rate", "N/A"),
        "notes": entry.get("notes", "")
    }

def resolve_exhibit_reliability(
    exhibit: Dict[str, Any],
    custom_base_configs: Optional[Dict[str, float]] = None
) -> Tuple[float, Dict[str, Any]]:
    """
    Resolve reliability starting from base value for evidence type,
    then apply legal and forensic integrity modifiers:
      - Hash verified (+0.05)
      - Chain of custody complete (+0.10 if True, -0.15 if False)
      - Sec 65B certificate present (+0.10 if True, -0.15 if missing on digital)
      - Source independent (+0.05 if True, -0.10 if False)
      - Quality rating ((rating - 3.0) * 0.05)
    Clamps between 0.10 and 0.99.
    """
    # 1. Check if analyst supplied manual override
    if exhibit.get("manual_reliability") is not None:
        val = max(0.10, min(0.99, float(exhibit["manual_reliability"])))
        return round(val, 3), {
            "evidence_type": exhibit.get("evidence_type", "document"),
            "base_value": round(val, 3),
            "manual_override": True,
            "modifiers_applied": {"manual_override": 0.0},
            "final_clamped": round(val, 3),
            "rationale": "Analyst manual reliability override"
        }

    evidence_type = str(exhibit.get("evidence_type") or "document")
    base_map = custom_base_configs or DEFAULT_BASE_RELIABILITY
    base_val = base_map.get(evidence_type, base_map.get("document", 0.70))

    modifiers = {}
    current = base_val

    # Hash verified
    if exhibit.get("hash_verified"):
        modifiers["hash_verified"] = +0.05
        current += 0.05

    # Chain of custody
    if exhibit.get("chain_of_custody_complete"):
        modifiers["chain_of_custody_complete"] = +0.08
        current += 0.08
    else:
        modifiers["chain_of_custody_incomplete"] = -0.12
        current -= 0.12

    # Section 65B Indian Evidence Act for electronic media (applies strictly to digital records)
    is_physical = exhibit.get("evidence_kind") == "physical"
    is_digital = not is_physical and evidence_type.upper() in ["CCTV", "CDR", "DOCUMENT", "AUDIO", "VIDEO"]

    if is_physical:
        if exhibit.get("chain_of_custody_complete"):
            modifiers["physical_seal_and_custody_intact"] = +0.06
            current += 0.06
        else:
            modifiers["physical_custody_gap_or_broken_seal"] = -0.20
            current -= 0.20
    elif is_digital:
        if exhibit.get("sec_65b_certificate_present"):
            modifiers["sec_65b_certified"] = +0.07
            current += 0.07
        else:
            modifiers["sec_65b_missing"] = -0.15
            current -= 0.15

    # Source independence
    if exhibit.get("source_independent", True):
        modifiers["source_independent"] = +0.05
        current += 0.05
    else:
        modifiers["source_dependent"] = -0.10
        current -= 0.10

    # Quality rating (1.0 to 5.0, default 3.0)
    quality = float(exhibit.get("quality_rating") or 3.0)
    quality_mod = (quality - 3.0) * 0.04
    if abs(quality_mod) > 0.001:
        modifiers["quality_rating"] = round(quality_mod, 3)
        current += quality_mod

    # Multilingual & Text Quality Forensic Modifiers:
    content_type = str(exhibit.get("content_type") or "printed").lower()
    text_quality = str(exhibit.get("text_quality_status") or "unreviewed").lower()
    is_low_conf = bool(exhibit.get("is_low_confidence", False))
    ocr_conf = float(exhibit.get("ocr_confidence") or 1.0)
    is_poor_audio = bool(exhibit.get("is_poor_audio", False))

    if content_type == "handwritten" and text_quality == "unreviewed":
        modifiers["unreviewed_handwriting"] = -0.15
        current -= 0.15
    elif (is_low_conf or ocr_conf < 0.70) and text_quality == "unreviewed":
        modifiers["unreviewed_low_confidence_ocr"] = -0.10
        current -= 0.10

    if is_poor_audio and text_quality == "unreviewed":
        modifiers["poor_audio_quality"] = -0.10
        current -= 0.10

    if text_quality == "reviewed":
        modifiers["human_reviewed_transcript"] = +0.08
        current += 0.08
    elif text_quality == "corrected":
        modifiers["human_corrected_transcript"] = +0.10
        current += 0.10

    # Police Document Structure & Completeness Forensic Modifier:
    if exhibit.get("document_type"):
        doc_pct = float(exhibit.get("document_completeness_pct", 100))
        if doc_pct < 60.0:
            penalty = -0.15
            modifiers["incomplete_police_memo_critical"] = penalty
            current += penalty
        elif doc_pct < 85.0:
            penalty = -0.08
            modifiers["incomplete_police_memo_minor"] = penalty
            current += penalty
        elif doc_pct >= 95.0:
            bonus = +0.05
            modifiers["complete_police_memo_verified"] = bonus
            current += bonus

    final_clamped = max(0.10, min(0.99, current))

    audit = {
        "evidence_type": evidence_type,
        "base_value": round(base_val, 3),
        "manual_override": False,
        "modifiers_applied": modifiers,
        "final_clamped": round(final_clamped, 3),
        "rationale": f"Base {evidence_type} ({base_val}) adjusted by forensic integrity checks."
    }
    return round(final_clamped, 3), audit

