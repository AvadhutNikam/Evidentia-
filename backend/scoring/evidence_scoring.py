def resolve_exhibit_dependency_multipliers(
    active_exhibits: List[Dict[str, Any]],
    discount_factor: float = 0.50
) -> Tuple[Dict[Any, float], Dict[str, Any]]:
    """
    CHANGE 5: Dependent Evidence Grouping & Damped Weighting
    ========================================================
    Combines exhibits that share a common underlying source (e.g., retold witness statements,
    a statement describing a CCTV clip, copies of the same report).
    Instead of adding each dependent exhibit in full (which artificially multiplies likelihoods),
    applies diminishing returns within each group:
      - Rank 1 (Primary exhibit): 100% weight (w_1 = 1.0)
      - Rank 2 (1st dependent retelling): 50% weight (w_2 = 0.50)
      - Rank 3 (2nd dependent retelling): 25% weight (w_3 = 0.25)
      - Rank j: discount_factor^(j-1)
    """
    groups: Dict[str, List[Dict[str, Any]]] = {}
    for ev in active_exhibits:
        grp = ev.get("dependency_group")
        if grp and str(grp).strip():
            grp_key = str(grp).strip()
            groups.setdefault(grp_key, []).append(ev)

    exhibit_multipliers = {ev["id"]: 1.0 for ev in active_exhibits}
    group_audits = {}

    for grp_key, grp_evs in groups.items():
        if len(grp_evs) <= 1:
            group_audits[grp_key] = {
                "group_name": grp_key,
                "exhibit_count": len(grp_evs),
                "exhibit_ids": [e["id"] for e in grp_evs],
                "discount_factor": discount_factor,
                "multipliers": {grp_evs[0]["id"]: 1.0},
                "total_effective_weight": 1.0,
                "undamped_weight": 1.0,
                "damping_applied": False,
                "note": "Single exhibit in dependency cluster; evaluated at 100% full weight."
            }
            continue

        # Sort exhibits in group: higher quality_rating or verified hash first
        sorted_grp = sorted(
            grp_evs,
            key=lambda e: (
                float(e.get("quality_rating") or 3.0),
                1 if e.get("hash_verified") else 0
            ),
            reverse=True
        )

        multipliers = {}
        total_eff = 0.0
        for idx, ev in enumerate(sorted_grp):
            w = round(discount_factor ** idx, 4)
            multipliers[ev["id"]] = w
            exhibit_multipliers[ev["id"]] = w
            total_eff += w

        group_audits[grp_key] = {
            "group_name": grp_key,
            "exhibit_count": len(grp_evs),
            "exhibit_ids": [e["id"] for e in sorted_grp],
            "discount_factor": discount_factor,
            "multipliers": multipliers,
            "total_effective_weight": round(total_eff, 3),
            "undamped_weight": float(len(grp_evs)),
            "damping_applied": True,
            "note": f"Dependency cluster of {len(grp_evs)} exhibits; primary at 100%, dependent exhibits discounted by {discount_factor}x per retelling."
        }

    return exhibit_multipliers, group_audits


def cluster_breakdown_rows_by_dependency(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    CHANGE 5: Groups dependent exhibits together in the breakdown.
    Exhibits with the same dependency_group appear consecutively, ordered by their rank/multiplier.
    Independent exhibits maintain their primary diagnostic/contribution ranking.
    """
    if not rows:
        return []

    grouped_by_key: Dict[str, List[Dict[str, Any]]] = {}
    independent_rows: List[Tuple[int, Dict[str, Any]]] = []
    group_first_seen: Dict[str, int] = {}

    for idx, r in enumerate(rows):
        grp = r.get("dependency_group")
        if grp and str(grp).strip():
            k = str(grp).strip()
            if k not in group_first_seen:
                group_first_seen[k] = idx
            grouped_by_key.setdefault(k, []).append(r)
        else:
            independent_rows.append((idx, r))

    # Sort items within each group by dependency_weight_multiplier descending (primary first)
    for k in grouped_by_key:
        grouped_by_key[k].sort(
            key=lambda x: (
                float(x.get("dependency_weight_multiplier") or 1.0),
                abs(float(x.get("contribution") or 0.0))
            ),
            reverse=True
        )

    # Recombine in order of appearance
    merged: List[Tuple[float, Dict[str, Any]]] = []
    for idx, r in independent_rows:
        merged.append((float(idx), r))

    for k, grp_items in grouped_by_key.items():
        base_idx = float(group_first_seen[k])
        for sub_i, item in enumerate(grp_items):
            item_copy = dict(item)
            item_copy["dependency_cluster_size"] = len(grp_items)
            item_copy["is_dependency_cluster"] = len(grp_items) > 1
            item_copy["is_cluster_primary"] = (sub_i == 0)
            merged.append((base_idx + (sub_i * 0.001), item_copy))

    merged.sort(key=lambda x: x[0])
    return [x[1] for x in merged]


