def detect_investigative_gaps(
    case: Optional[Dict[str, Any]],
    hypotheses: List[Dict[str, Any]],
    exhibits: List[Dict[str, Any]],
    assessments: List[Dict[str, Any]],
    events: Optional[List[Dict[str, Any]]] = None,
    contradictions: Optional[List[Dict[str, Any]]] = None
) -> List[Dict[str, Any]]:
    """
    CHANGE 7: Gap Detection Rule Engine
    ====================================
    Evaluates 5 rule checks across the case and returns actionable task objects:
      1. Named suspect has no alibi check or forensic comparison
      2. Key exhibit is missing a custody record or Sec 65B/63 certificate
      3. An approver or witness statement has no independent corroboration
      4. A time window has no CCTV, call or location data
      5. A hypothesis has only one supporting exhibit
    """
    gaps = []

    # 1. Rule 1: A named suspect has no alibi check or forensic comparison
    for h in hypotheses:
        if h.get("is_unknown") or (h.get("title") and "unknown" in h["title"].lower()):
            continue
        h_id = h["id"]
        h_title = h.get("title", f"Hypothesis #{h_id}")

        has_alibi_or_forensics = False
        for a in assessments:
            if str(a.get("hypothesis_id")) == str(h_id):
                ev_id = a.get("evidence_id")
                ev_obj = next((e for e in exhibits if str(e.get("id")) == str(ev_id)), {})
                ev_type = str(ev_obj.get("evidence_type", a.get("evidence_type", ""))).lower()
                f_cat = str(a.get("finding_category", "")).lower()
                c_type = str(a.get("clearing_type", "")).lower()

                if ev_type in ["dna", "fingerprint", "ballistics", "digital", "cdr"] or \
                   any(k in f_cat for k in ["dna", "fingerprint", "alibi", "cctv", "cdr"]) or \
                   any(k in c_type for k in ["alibi", "dna", "exclusion", "location"]):
                    has_alibi_or_forensics = True
                    break

        if not has_alibi_or_forensics:
            gaps.append({
                "gap_id": f"gap_no_alibi_or_forensic_{h_id}",
                "rule_code": "GAP_NO_ALIBI_OR_FORENSIC",
                "rule_title": "Named Suspect Lacks Alibi Check or Forensic Comparison",
                "target_type": "hypothesis",
                "target_id": h_id,
                "target_title": h_title,
                "severity": "high",
                "priority": "High",
                "description": f"Suspect '{h_title}' has no recorded alibi verification or forensic comparison (DNA, fingerprint, digital forensics).",
                "recommended_task": f"Subpoena CDR cell tower records and schedule formal alibi verification interview for {h_title}.",
                "action_category": "alibi_forensics",
                "default_assigned_to": "Field Investigation Team"
            })

    # 2. Rule 2: Key exhibit is missing a custody record or Sec 65B certificate
    for ev in exhibits:
        ev_id = ev.get("id")
        title = ev.get("title") or ev.get("file_name", f"Exhibit #{ev_id}")
        ev_type = str(ev.get("evidence_type", "")).lower()

        is_key = ev_type in ["dna", "cctv", "cdr", "fingerprint", "digital", "video", "audio"] or \
                 bool(ev.get("is_critical"))

        if is_key:
            custody_missing = not bool(ev.get("chain_of_custody_complete") or ev.get("chain_of_custody_verified"))
            sec65b_missing = (ev_type in ["cctv", "cdr", "digital", "video", "audio"]) and \
                             not bool(ev.get("sec_65b_certificate_present") or ev.get("sec_65b_certificate"))

            missing_items = []
            if custody_missing:
                missing_items.append("Chain of Custody record")
            if sec65b_missing:
                missing_items.append("Section 65B/63 Electronic Evidence Certificate")

            if missing_items:
                gaps.append({
                    "gap_id": f"gap_missing_custody_sec65b_{ev_id}",
                    "rule_code": "GAP_MISSING_CUSTODY_OR_SEC65B",
                    "rule_title": "Key Exhibit Missing Custody Record or Sec 65B Certificate",
                    "target_type": "evidence",
                    "target_id": ev_id,
                    "target_title": title,
                    "severity": "high",
                    "priority": "High",
                    "description": f"Key exhibit '{title}' is missing: {', '.join(missing_items)}. Risk of procedural inadmissibility under Indian Evidence Act Sec 65B / BSA Sec 63.",
                    "recommended_task": f"Obtain {', '.join(missing_items)} for Exhibit #{ev_id} ('{title}').",
                    "action_category": "legal_compliance",
                    "default_assigned_to": "Evidence Custodian / Court Liaison"
                })

    # 3. Rule 3: An approver or witness statement has no independent corroboration
    for ev in exhibits:
        ev_id = ev.get("id")
        title = ev.get("title") or ev.get("file_name", f"Exhibit #{ev_id}")
        ev_type = str(ev.get("evidence_type", "")).lower()
        title_lower = title.lower()

        is_testimonial = ev_type in ["witness", "confession"] or \
                         any(w in title_lower for w in ["statement", "confession", "approver", "disclosure"])

        if is_testimonial:
            has_corroboration = bool(ev.get("source_independent")) and not bool(ev.get("is_uncorroborated"))
            if not has_corroboration or ev.get("source_independent") is False:
                gaps.append({
                    "gap_id": f"gap_uncorroborated_statement_{ev_id}",
                    "rule_code": "GAP_UNCORROBORATED_STATEMENT",
                    "rule_title": "Approver or Witness Statement Lacks Independent Corroboration",
                    "target_type": "evidence",
                    "target_id": ev_id,
                    "target_title": title,
                    "severity": "medium",
                    "priority": "Medium",
                    "description": f"Statement '{title}' relies on uncorroborated testimonial assertion without independent forensic, digital, or physical verification.",
                    "recommended_task": f"Corroborate statement '{title}' with independent CDR logs, financial records, or CCTV footage.",
                    "action_category": "witness_corroboration",
                    "default_assigned_to": "Field Detective"
                })

    # 4. Rule 4: A time window has no CCTV, call or location data
    electronic_location_exhibits = [
        e for e in exhibits
        if str(e.get("evidence_type", "")).lower() in ["cctv", "cdr", "gps", "digital", "video"]
    ]
    if len(electronic_location_exhibits) == 0:
        gaps.append({
            "gap_id": "gap_missing_timeline_coverage",
            "rule_code": "GAP_MISSING_TIMELINE_COVERAGE",
            "rule_title": "Incident Time Window Lacks Electronic Telemetry or Surveillance",
            "target_type": "timeline",
            "target_id": None,
            "target_title": "Incident Window",
            "severity": "high",
            "priority": "High",
            "description": "The incident timeline contains no CCTV surveillance, mobile cell tower (CDR), or vehicle GPS location data.",
            "recommended_task": "Requisition intersection CCTV camera archives and mobile tower CDR dump for the crime window.",
            "action_category": "timeline_telemetry",
            "default_assigned_to": "Cyber & Technical Cell"
        })

    # 5. Rule 5: A hypothesis has only one supporting exhibit
    for h in hypotheses:
        if h.get("is_unknown") or (h.get("title") and "unknown" in h["title"].lower()):
            continue
        h_id = h["id"]
        h_title = h.get("title", f"Hypothesis #{h_id}")

        supporting_exhibits = []
        for a in assessments:
            if str(a.get("hypothesis_id")) == str(h_id):
                cls = str(a.get("classification", "")).lower()
                eff_lr_val = a.get("effective_lr")
                eff_lr = float(eff_lr_val) if eff_lr_val is not None else 1.0
                if cls in ["strong_support", "moderate_support", "weak_support"] or eff_lr > 1.2:
                    supporting_exhibits.append(a.get("evidence_id"))

        unique_supporting = set(supporting_exhibits)
        if len(unique_supporting) == 1:
            single_ev_id = list(unique_supporting)[0]
            single_ev = next((e for e in exhibits if str(e.get("id")) == str(single_ev_id)), {})
            single_title = single_ev.get("title") or single_ev.get("file_name", f"Exhibit #{single_ev_id}")
            gaps.append({
                "gap_id": f"gap_single_supporting_{h_id}",
                "rule_code": "GAP_SINGLE_SUPPORTING_EXHIBIT",
                "rule_title": "Hypothesis Has Only One Supporting Exhibit",
                "target_type": "hypothesis",
                "target_id": h_id,
                "target_title": h_title,
                "severity": "medium",
                "priority": "Medium",
                "description": f"Hypothesis '{h_title}' has only one supporting exhibit ('{single_title}'). Theory is vulnerable to single-source failure.",
                "recommended_task": f"Obtain independent secondary corroborating evidence for hypothesis '{h_title}'.",
                "action_category": "hypothesis_corroboration",
                "default_assigned_to": "Investigative Analyst"
            })

    return gaps


