def compute_score_deltas(
    current_scores: Dict[str, float],
    previous_scores: Dict[str, float]
) -> Dict[str, Dict[str, float]]:
    """Calculates directional shift in hypothesis probability between two runs."""
    deltas = {}
    all_keys = set(current_scores.keys()) | set(previous_scores.keys())
    for k in all_keys:
        curr = current_scores.get(k, 0.0)
        prev = previous_scores.get(k, 0.0)
        deltas[k] = {
            "previous": prev,
            "current": curr,
            "delta": round(curr - prev, 3),
            "pct_change": round(((curr - prev) / prev * 100.0) if prev > 0 else 0.0, 2)
        }
    return deltas
